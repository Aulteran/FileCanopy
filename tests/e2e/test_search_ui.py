"""M11 in a real browser: the search box finds a file by name and by its text (indexed in the
background), shows a snippet, and opens the file or its folder. Generated bytes only."""

import re

import pytest
from playwright.sync_api import Browser, expect
from support import World, sign_in, upload

pytestmark = pytest.mark.e2e


def test_search_by_name_and_by_text(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    upload(page, "garden-plan.txt", b"Plant the rhubarb beside the compost heap in spring.")
    expect(page.get_by_role("row").filter(has_text="garden-plan.txt")).to_be_visible()

    box = page.get_by_role("searchbox", name="Search files")
    box.fill("garden")
    box.press("Enter")
    expect(page.get_by_role("heading", name="Search results")).to_be_visible()
    expect(page.get_by_role("link", name="garden-plan.txt")).to_be_visible()
    expect(page).to_have_url(re.compile(r"/search\?q=garden"))

    # the text is read in the background: wait for it, searching again until it shows
    found = False
    box = page.get_by_role("searchbox", name="Search files")
    box.fill("rhubarb")
    box.press("Enter")
    for _ in range(40):
        page.wait_for_timeout(500)
        if page.get_by_text("beside the compost heap").count():
            found = True
            break
        page.wait_for_timeout(1500)
        page.reload()  # the same address would not search again by itself
    if not found:  # say what the server knows, so a failure explains itself
        docs = world.stack.sql("select count(*) from search_doc")
        jobs = world.stack.sql("select state || ':' || coalesce(error, '-') from search_job")
        api = page.request.get(page.url.split("/search")[0] + "/api/v1/search?q=rhubarb")
        body = world.stack.sql("select left(body, 80) || '|' || source from search_doc")
        raise AssertionError(
            f"text never found; rows={docs}; jobs={jobs!r}; doc={body!r}; "
            f"api={api.status} {api.text()[:300]!r}; page={page.inner_text('main')[:300]!r}"
        )
    expect(page.get_by_text("Text", exact=True).first).to_be_visible()
    page.get_by_role("link", name="Show in folder").first.click()
    expect(page.get_by_role("row").filter(has_text="garden-plan.txt")).to_be_visible()

    box = page.get_by_role("searchbox", name="Search files")
    box.fill("zzzz-no-such-thing")
    box.press("Enter")
    expect(page.get_by_text("Nothing matches")).to_be_visible()


def test_another_person_does_not_see_the_result(world: World, browser: Browser) -> None:
    alice = sign_in(browser, world, world.alice_mail)
    upload(alice, "alice-only.txt", b"unique-token-quokka in alices own folder")
    expect(alice.get_by_role("row").filter(has_text="alice-only.txt")).to_be_visible()
    bob = sign_in(browser, world, world.bob_mail)
    box = bob.get_by_role("searchbox", name="Search files")
    box.fill("quokka")
    box.press("Enter")
    expect(bob.get_by_text("Nothing matches")).to_be_visible()
    box.fill("alice-only")
    box.press("Enter")
    expect(bob.get_by_text("Nothing matches")).to_be_visible()
