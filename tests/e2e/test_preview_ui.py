"""M10 in a real browser (no converter container in this stack): Word files say "download
instead", a ZIP opens as an inert listing, a picture gets a thumbnail in the details panel, and
Private files ask for the local-processing opt-in that Preview settings can withdraw. The real
LibreOffice container is exercised by tests/integration/converter. Generated bytes only."""

import io
import re
import zipfile

import pytest
from playwright.sync_api import Browser, Page, expect
from support import World, api_status, new_folder, open_folder, select, sign_in, upload
from test_viewer_ui import PNG_1X1, open_file

pytestmark = pytest.mark.e2e


def make_zip() -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("docs/readme.txt", "hello")
        z.writestr("../escape.txt", "x")
        z.writestr("<script>alert(1)</script>.txt", "x")
    return buf.getvalue()


def child_id(page: Page, world: World, parent: str, name: str) -> str:
    r = page.request.get(f"{world.base}/api/v1/nodes/{parent}/children?limit=500")
    for item in r.json()["items"]:
        if item["name"] == name:
            return str(item["id"])
    raise AssertionError(f"{name} not found")


def test_word_file_without_the_converter_offers_download(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    upload(page, "letter.docx", b"PK\x03\x04 pretend word document")
    expect(page.get_by_role("row").filter(has_text="letter.docx")).to_be_visible()
    open_file(page, "letter.docx")
    expect(page.get_by_role("heading", name="No preview here")).to_be_visible()
    expect(page.get_by_text("optional add-on that is not running")).to_be_visible()
    expect(page.get_by_role("link", name="Download").first).to_be_visible()


def test_zip_opens_as_an_inert_listing(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    dialogs: list[str] = []
    page.on("dialog", lambda d: (dialogs.append(d.message), d.dismiss()))
    upload(page, "bundle.zip", make_zip())
    expect(page.get_by_role("row").filter(has_text="bundle.zip")).to_be_visible()
    open_file(page, "bundle.zip")
    expect(page.get_by_text("Nothing has been opened or unpacked")).to_be_visible()
    expect(page.get_by_role("cell", name="docs/readme.txt")).to_be_visible()
    expect(page.get_by_role("cell", name=re.compile(r"\.\./escape\.txt.*not safe"))).to_be_visible()
    # a hostile name is text, never markup
    expect(page.get_by_role("cell", name="<script>alert(1)</script>.txt")).to_be_visible()
    assert page.locator("table script").count() == 0 and dialogs == []


def test_picture_gets_a_thumbnail_in_the_details_panel(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    upload(page, "tiny.png", PNG_1X1)
    expect(page.get_by_role("row").filter(has_text="tiny.png")).to_be_visible()
    select(page, "tiny.png")
    thumb = page.locator("img.thumb")
    expect(thumb).to_be_visible()
    page.wait_for_function("() => document.querySelector('img.thumb').naturalWidth > 0")


def test_private_files_need_the_opt_in_and_it_can_be_withdrawn(
    world: World, browser: Browser
) -> None:
    page = sign_in(browser, world, world.alice_mail)
    new_folder(page, "Secret papers")
    folder = child_id(page, world, world.alice_root, "Secret papers")
    assert api_status(page, "PUT", f"/api/v1/nodes/{folder}/privacy", {"label": "private"}) == 200
    open_folder(page, "Secret papers")
    upload(page, "inside.zip", make_zip())
    expect(page.get_by_role("row").filter(has_text="inside.zip")).to_be_visible()
    # a thumbnail is not made for a protected picture until the opt-in is given
    upload(page, "photo.png", PNG_1X1)
    expect(page.get_by_role("row").filter(has_text="photo.png")).to_be_visible()
    select(page, "photo.png")
    page.wait_for_timeout(500)
    expect(page.locator("img.thumb")).to_have_count(0)

    open_file(page, "inside.zip")
    expect(page.get_by_role("heading", name="Allow previews of protected files?")).to_be_visible()
    page.get_by_role("button", name="Allow on this server").click()
    expect(page.get_by_role("cell", name="docs/readme.txt")).to_be_visible()

    # withdraw it in Preview settings: the same file asks again
    page.get_by_role("button", name="Preview settings").click()
    dialog = page.get_by_role("dialog", name="Preview settings")
    box = dialog.get_by_label("Let this server make previews of my Private and Confidential files")
    expect(box).to_be_checked()
    box.uncheck()
    dialog.get_by_role("button", name="Close").click()
    page.reload()
    expect(page.get_by_role("heading", name="Allow previews of protected files?")).to_be_visible()
