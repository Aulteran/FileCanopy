pytestmark = pytest.mark.e2e


def make_pdf(pages: int, js: str | None = None) -> bytes:
    """A small valid PDF with one line of text per page (standard Helvetica font)."""
    objs: list[bytes] = []
    kids = " ".join(f"{4 + 2 * i} 0 R" for i in range(pages))
    action = f"/OpenAction << /S /JavaScript /JS ({js}) >> " if js else ""
    objs.append(f"<< /Type /Catalog /Pages 2 0 R {action}>>".encode())
    objs.append(f"<< /Type /Pages /Kids [{kids}] /Count {pages} >>".encode())
    objs.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")  # object 3
    for i in range(pages):
        page, content = 4 + 2 * i, 5 + 2 * i
        objs.append(
            f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 300 400] /Contents {content} 0 R "
            f"/Resources << /Font << /F1 3 0 R >> >> >>".encode()
        )
        text = f"BT /F1 24 Tf 40 300 Td (Canopy page {i + 1}) Tj ET".encode()
        objs.append(b"<< /Length %d >>\nstream\n" % len(text) + text + b"\nendstream")
        assert page == len(objs) - 1
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for n, body in enumerate(objs, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % n + body + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    for off in offsets:
        out += b"%010d 00000 n \n" % off
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    return bytes(out)


PNG_1X1 = bytes.fromhex(
    "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c489"
    "0000000d49444154789c6360f8cfc00000030101009f0d1e8b0000000049454e44ae426082"
)
SCRIPTED_SVG = (
    b'<svg xmlns="http://www.w3.org/2000/svg" width="40" height="40">'
    b'<script>alert("svg-ran")</script><rect width="40" height="40" fill="green"/></svg>'
)


def open_file(page: Page, name: str) -> None:
    row = page.get_by_role("row").filter(has_text=name)
    row.get_by_role("link", name=name).click()
    expect(page).to_have_url(re.compile(r"/view/"))


def test_pdf_opens_scrolls_and_zooms_with_no_third_party_requests(
    world: World, browser: Browser
) -> None:
    page = sign_in(browser, world, world.alice_mail)
    dialogs: list[str] = []
    page.on("dialog", lambda d: (dialogs.append(d.message), d.dismiss()))
    foreign: list[str] = []
    page.on(
        "request",
        lambda r: (
            foreign.append(r.url) if not r.url.startswith((world.base, "blob:", "data:")) else None
        ),
    )
    bad_csp: list[str] = []
    page.on(
        "console", lambda m: bad_csp.append(m.text) if "Content Security Policy" in m.text else None
    )

    upload(page, "canopy.pdf", make_pdf(6))
    upload(page, "scripted.pdf", make_pdf(1, js="app.alert('pdf-ran')"))
    expect(page.get_by_role("row").filter(has_text="scripted.pdf")).to_be_visible()

    open_file(page, "canopy.pdf")
    expect(page.get_by_role("heading", level=1, name="canopy.pdf")).to_be_visible()
    expect(page.get_by_text("Page 1 of 6")).to_be_visible()
    first = page.get_by_role("img", name="Page 1")
    expect(first).to_be_visible()
    width_before = first.bounding_box()["width"]  # type: ignore[index]
    # real drawing happened on the canvas (not blank white)
    page.wait_for_function(
        """() => { const c = document.querySelector('canvas');
          if (!c || !c.width) return false;
          const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
          for (let i = 0; i < d.length; i += 4) if (d[i] < 128) return true; return false; }"""
    )
    page.get_by_role("button", name="Zoom in").click()
    expect(page.get_by_text("125%")).to_be_visible()
    page.wait_for_function(
        "w => document.querySelector('[data-page=\\'1\\']').getBoundingClientRect().width > w + 5",
        arg=width_before,
    )
    # scroll to the last page: the indicator follows
    page.locator("[data-page='6']").scroll_into_view_if_needed()
    expect(page.get_by_text("Page 6 of 6")).to_be_visible()
    expect(page.get_by_role("img", name="Page 6")).to_be_visible()

    # one "viewed" entry for the open, in the activity panel
    page.get_by_role("button", name="← Back").click()
    expect(page).not_to_have_url(re.compile(r"/view/"))
    select(page, "canopy.pdf")
    page.get_by_role("button", name="Show history").click()
    history = page.get_by_role("list", name="History, newest first")
    expect(history).to_contain_text("Viewed by")
    assert history.get_by_text("Viewed by").count() == 1

    # a PDF with JavaScript is shown as a document; its script never runs
    open_file(page, "scripted.pdf")
    expect(page.get_by_role("img", name="Page 1")).to_be_visible()
    page.wait_for_timeout(1000)
    assert dialogs == [], dialogs
    assert foreign == [], foreign
    assert bad_csp == [], bad_csp


def test_pictures_text_and_tables_never_run_or_inject_markup(
    world: World, browser: Browser
) -> None:
    page = sign_in(browser, world, world.alice_mail)
    dialogs: list[str] = []
    page.on("dialog", lambda d: (dialogs.append(d.message), d.dismiss()))
    upload(page, "dot.png", PNG_1X1)
    upload(page, "evil.svg", SCRIPTED_SVG)
    upload(page, "notes.txt", b"hello <img src=x onerror=alert('xss')> world\nsecond line\n")
    upload(page, "sheet.csv", b'name,note\nAda,"<b>bold</b>"\nBob,"x, y"\n')
    expect(page.get_by_role("row").filter(has_text="sheet.csv")).to_be_visible()

    open_file(page, "dot.png")
    img = page.locator("img.viewer-image")
    expect(img).to_be_visible()
    page.wait_for_function("() => document.querySelector('img.viewer-image').naturalWidth > 0")
    page.go_back()

    open_file(page, "evil.svg")
    expect(page.locator("img.viewer-image")).to_be_visible()
    expect(page.locator("svg")).to_have_count(0)  # never inlined into the page
    page.go_back()

    open_file(page, "notes.txt")
    expect(page.locator("pre.viewer-text")).to_contain_text("<img src=x onerror=alert('xss')>")
    expect(page.locator("pre.viewer-text img")).to_have_count(0)
    page.go_back()

    open_file(page, "sheet.csv")
    cell = page.get_by_role("cell", name="<b>bold</b>")
    expect(cell).to_be_visible()
    expect(page.locator("td b")).to_have_count(0)
    expect(page.get_by_role("cell", name="x, y")).to_be_visible()
    page.wait_for_timeout(500)
    assert dialogs == [], dialogs


def test_unsupported_damaged_and_forged_files_get_a_friendly_page(
    world: World, browser: Browser
) -> None:
    page = sign_in(browser, world, world.alice_mail)
    upload(page, "report.docx", b"PK\x03\x04 not really")
    upload(page, "broken.pdf", make_pdf(3)[:200])  # truncated
    upload(page, "fake.png", b"<html>not a png</html>")
    expect(page.get_by_role("row").filter(has_text="fake.png")).to_be_visible()

    # a type the viewer does not handle: no link into the viewer, download only
    select(page, "report.docx")
    expect(page.get_by_role("link", name="Open")).to_have_count(0)
    expect(page.get_by_role("link", name="Download")).to_be_visible()

    page.goto(f"{world.base}/view/{_node_id(page, world, 'report.docx')}")
    expect(page.get_by_role("heading", name="No preview here")).to_be_visible()
    expect(page.get_by_role("link", name="Download").first).to_be_visible()

    page.goto(world.base + "/")
    open_file(page, "broken.pdf")
    expect(page.get_by_role("heading", name="This file cannot be shown")).to_be_visible()
    expect(page.get_by_role("link", name="Download").first).to_be_visible()

    page.go_back()
    open_file(page, "fake.png")
    expect(page.get_by_role("heading", name="This file cannot be shown")).to_be_visible()


def test_viewer_headers_csp_and_other_people(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    upload(page, "h.pdf", make_pdf(1))
    expect(page.get_by_role("row").filter(has_text="h.pdf")).to_be_visible()
    node = _node_id(page, world, "h.pdf")

    shell = page.request.get(f"{world.base}/view/{node}")
    csp = shell.headers["content-security-policy"]
    assert "worker-src 'self'" in csp and "default-src 'self'" in csp
    assert "unsafe-eval" not in csp and "unsafe-inline" not in csp
    assert "frame-ancestors 'none'" in csp
    asset = page.request.get(f"{world.base}/pdfjs/standard_fonts/LiberationSans-Regular.ttf")
    assert asset.status == 200 and len(asset.body()) > 10_000
    assert (
        page.request.get(f"{world.base}/pdfjs/wasm/quickjs-eval.wasm")
        .headers.get("content-type", "")
        .startswith("text/html")
    )  # the scripting sandbox is not shipped (SPA fallback page)

    raw = page.request.get(f"{world.base}/api/v1/nodes/{node}/view", headers={"Range": "bytes=0-7"})
    assert raw.status == 206 and raw.body() == b"%PDF-1.4"
    assert raw.headers["content-disposition"] == "inline"

    # someone else gets the same refusal as for a download
    bob = sign_in(browser, world, world.bob_mail)
    r = bob.request.get(f"{world.base}/api/v1/nodes/{node}/view")
    assert r.status == 403
    bob.goto(f"{world.base}/view/{node}")
    expect(bob.get_by_role("alert")).to_contain_text("do not have access")


def _node_id(page: Page, world: World, name: str) -> str:
    r = page.request.get(f"{world.base}/api/v1/nodes/{world.alice_root}/children?limit=500")
    for item in r.json()["items"]:
        if item["name"] == name:
            return str(item["id"])
    raise AssertionError(f"{name} not found")
