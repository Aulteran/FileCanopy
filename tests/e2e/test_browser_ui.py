"""M05 in a real browser (Playwright, Chromium) against the real stack.

Covers the first-run setup and sign-in screens, folder CRUD (create, upload, download, rename,
move, copy) checked against the real files on the bind-mounted library, keyboard operation, a
phone-sized viewport, and the forbidden cases: the UI hides or disables what the server would
refuse, and the server refuses the same calls when they are made directly.

Tests run in file order and share one stack; the first one performs the first-run setup. Random
credentials and generated bytes only.
"""

