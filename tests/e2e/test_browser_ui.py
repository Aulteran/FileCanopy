def test_folder_crud_matches_real_files(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    expect(page.get_by_text("This folder is empty")).to_be_visible()

    new_folder(page, "Docs")
    new_folder(page, "Archive")
    assert (disk / "Docs").is_dir()

    # a name that already exists is refused with a readable message and the dialog stays open
    page.get_by_role("button", name="New folder").click()
    dialog = page.get_by_role("dialog", name="New folder")
    dialog.get_by_label("Folder name").fill("Docs")
    dialog.get_by_role("button", name="Create").click()
    expect(dialog.get_by_role("alert")).to_have_text("An item with that name already exists here.")
    dialog.get_by_role("button", name="Cancel").click()

    open_folder(page, "Docs")
    payload = os.urandom(3 * 1024 * 1024)
    upload(page, "report.bin", payload)
    expect(row(page, "report.bin")).to_be_visible()
    assert (disk / "Docs" / "report.bin").read_bytes() == payload

    # uploading the same name again is a conflict the user can resolve; nothing is overwritten
    upload(page, "report.bin", b"second")
    uploads = page.get_by_role("list", name="Uploads")
    expect(uploads.get_by_text("already exists")).to_be_visible()
    uploads.get_by_role("button", name="Keep both").click()
    expect(row(page, "report (2).bin")).to_be_visible()
    assert (disk / "Docs" / "report (2).bin").read_bytes() == b"second"
    assert (disk / "Docs" / "report.bin").read_bytes() == payload

    select(page, "report.bin")
    with page.expect_download() as download:
        page.get_by_role("link", name="Download").click()
    assert Path(download.value.path()).read_bytes() == payload

    page.get_by_role("button", name="Rename").click()
    dialog = page.get_by_role("dialog", name="Rename")
    dialog.get_by_label("New name").fill("final.bin")
    dialog.get_by_role("button", name="Rename").click()
    expect(row(page, "final.bin")).to_be_visible()
    assert (disk / "Docs" / "final.bin").read_bytes() == payload
    assert not (disk / "Docs" / "report.bin").exists()

    select(page, "final.bin")
    page.get_by_role("button", name="Copy…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Copy"))
    dialog.get_by_role("button", name="Archive").click()
    # Wait for the chosen folder's metadata before confirming; its async load/impact check can
    # otherwise change button readiness between Playwright's pointer-down and pointer-up.
    expect(dialog.get_by_text(re.compile(r"Destination: .*Archive$"))).to_be_visible()
    expect(dialog.get_by_role("button", name="Copy here")).to_be_enabled()
    with page.expect_response(
        lambda response: response.request.method == "POST" and response.url.endswith("/copy")
    ) as copied:
        dialog.get_by_role("button", name="Copy here").click()
    assert copied.value.status == 201, copied.value.text()
    expect(dialog).to_be_hidden()
    assert (disk / "Archive" / "final.bin").read_bytes() == payload
    assert (disk / "Docs" / "final.bin").read_bytes() == payload

    # moving onto a name that is taken is refused and explained
    select(page, "final.bin")
    page.get_by_role("button", name="Move…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Move"))
    dialog.get_by_role("button", name="Archive").click()
    expect(dialog.get_by_text(re.compile(r"Destination: .*Archive$"))).to_be_visible()
    dialog.get_by_role("button", name="Move here").click()
    expect(dialog.get_by_role("alert")).to_have_text("An item with that name already exists here.")
    dialog.get_by_role("button", name="Cancel").click()
    assert (disk / "Docs" / "final.bin").exists()
    page.close()


def test_move_between_folders(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    open_folder(page, "Docs")
    select(page, "report (2).bin")
    page.get_by_role("button", name="Move…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Move"))
    dialog.get_by_role("button", name="Archive").click()
    expect(dialog.get_by_text(re.compile(r"Destination: .*Archive$"))).to_be_visible()
    dialog.get_by_role("button", name="Move here").click()
    expect(dialog).to_be_hidden()
    expect(row(page, "report (2).bin")).to_have_count(0)
    assert (disk / "Archive" / "report (2).bin").read_bytes() == b"second"
    assert not (disk / "Docs" / "report (2).bin").exists()

    # uploading over an existing name never overwrites it
    crumbs(page).get_by_role("link", name="My files").click()
    open_folder(page, "Archive")
    upload(page, "final.bin", b"other")
    expect(page.get_by_role("list", name="Uploads").get_by_text("already exists")).to_be_visible()
    assert (disk / "Archive" / "final.bin").stat().st_size == 3 * 1024 * 1024
    page.close()


def test_single_selection_system(browser: Browser, world: World) -> None:
    """Row clicks and checkboxes are one selection: same ticks, same panels, bulk Copy works."""
    page = sign_in(browser, world, world.alice_mail)
    rows = page.locator("tbody tr")
    expect(rows).to_have_count(2)  # Archive, Docs
    boxes = page.get_by_role("checkbox")
    details = page.get_by_role("complementary", name="Details")

    # clicking a row ticks its box and shows the normal details panel
    select(page, "Docs")
    expect(row(page, "Docs").get_by_role("checkbox")).to_be_checked()
    expect(details.get_by_role("button", name="Rename")).to_be_visible()

    # ticking a second box (after a row click) gives the bulk panel, not a broken one
    row(page, "Archive").get_by_role("checkbox").check()
    expect(details.get_by_role("heading", name="2 items selected")).to_be_visible()
    for name in ("Move…", "Copy…", "Move to Trash", "Clear selection"):
        expect(details.get_by_role("button", name=name)).to_be_visible()

    # unticking one goes back to the single-item panel
    row(page, "Archive").get_by_role("checkbox").uncheck()
    expect(details.get_by_role("button", name="Rename")).to_be_visible()
    expect(row(page, "Docs").get_by_role("checkbox")).to_be_checked()

    # a plain row click replaces the selection (only that row stays ticked)
    select(page, "Archive")
    expect(row(page, "Archive").get_by_role("checkbox")).to_be_checked()
    expect(row(page, "Docs").get_by_role("checkbox")).not_to_be_checked()

    # select-all ticks every row and offers the bulk panel
    boxes.first.check()
    expect(details.get_by_role("heading", name="2 items selected")).to_be_visible()
    details.get_by_role("button", name="Clear selection").click()
    expect(row(page, "Docs").get_by_role("checkbox")).not_to_be_checked()
    page.close()


