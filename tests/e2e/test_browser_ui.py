"""M05 in a real browser (Playwright, Chromium) against the real stack.

Covers the first-run setup and sign-in screens, folder CRUD (create, upload, download, rename,
move, copy) checked against the real files on the bind-mounted library, keyboard operation, a
phone-sized viewport, and the forbidden cases: the UI hides or disables what the server would
refuse, and the server refuses the same calls when they are made directly.

Tests run in file order and share one stack; the first one performs the first-run setup. Random
credentials and generated bytes only.
"""

import os
import re
import uuid
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest
from playwright.sync_api import Browser, Locator, Page, expect, sync_playwright
from test_auth_stack import PASSWORD, Client
from test_stack import Stack
from test_storage_stack import invite_and_login, root_node, setup_admin, user_id

pytestmark = pytest.mark.e2e

expect.set_options(timeout=15_000)


@dataclass
class World:
    stack: Stack
    base: str
    alice_mail: str
    bob_mail: str
    alice: Client
    alice_root: str
    alice_disk: Path


@pytest.fixture(scope="session")
def browser() -> Iterator[Browser]:
    with sync_playwright() as p:
        b = p.chromium.launch()
        yield b
        b.close()


@pytest.fixture(scope="session")
def world(stack: Stack) -> World:
    admin = setup_admin(stack)
    tag = uuid.uuid4().hex[:6]
    alice_mail, bob_mail = f"alice{tag}@example.com", f"bob{tag}@example.com"
    alice = invite_and_login(stack, admin, alice_mail)
    invite_and_login(stack, admin, bob_mail)
    uid = user_id(stack, alice_mail)
    return World(
        stack,
        f"http://127.0.0.1:{stack.port}",
        alice_mail,
        bob_mail,
        alice,
        root_node(stack, f"personal/{uid}"),
        stack.library / "personal" / uid,
    )


def sign_in(browser: Browser, w: World, email: str, **ctx: Any) -> Page:
    page = browser.new_context(**ctx).new_page()
    page.goto(w.base + "/")
    page.get_by_label("Email").fill(email)
    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Sign in").click()
    expect(page.get_by_role("navigation", name="Locations")).to_be_visible()
    return page


def api_status(page: Page, method: str, path: str, body: Any = None) -> int:
    """A direct API call made from the signed-in page (cookie, CSRF token and Origin included)."""
    status = page.evaluate(
        """async ([method, path, body]) => {
          const s = await (await fetch('/api/v1/auth/session')).json();
          const r = await fetch(path, {
            method,
            body: body === null ? undefined : JSON.stringify(body),
            headers: {'X-CSRF-Token': s.csrf_token, 'Content-Type': 'application/json'},
          });
          return r.status;
        }""",
        [method, path, body],
    )
    return int(status)


def row(page: Page, name: str) -> Locator:
    return page.get_by_role("row").filter(has_text=name)


def select(page: Page, name: str) -> None:
    row(page, name).locator("td").nth(1).click()  # the size cell: not the folder link


def crumbs(page: Page) -> Locator:
    return page.get_by_role("navigation", name="Breadcrumb")


def upload(page: Page, name: str, data: bytes) -> None:
    page.get_by_test_id("upload-input").set_input_files(
        {"name": name, "mimeType": "application/octet-stream", "buffer": data}
    )


def new_folder(page: Page, name: str) -> None:
    page.get_by_role("button", name="New folder").click()
    dialog = page.get_by_role("dialog", name="New folder")
    dialog.get_by_label("Folder name").fill(name)
    dialog.get_by_role("button", name="Create").click()
    expect(row(page, name)).to_be_visible()


def open_folder(page: Page, name: str) -> None:
    row(page, name).get_by_role("link", name=name).click()
    expect(crumbs(page).get_by_text(name)).to_be_visible()


def test_first_run_setup_and_sign_in(stack: Stack, browser: Browser) -> None:
    base = f"http://127.0.0.1:{stack.port}"
    page = browser.new_context().new_page()
    page.goto(base + "/")
    expect(page.get_by_role("heading", name="Create the administrator")).to_be_visible()
    logs = stack.compose("logs", "--no-color", "api").stdout
    token = re.findall(r"FIRST-RUN SETUP TOKEN[^:]*: ([\w-]+)", logs)[-1]

    page.get_by_label("Setup token").fill("wrong-token")
    page.get_by_label("Your name").fill("Ada")
    page.get_by_label("Email").fill("admin@example.com")
    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Create account").click()
    expect(page.get_by_role("alert").filter(has_text="setup token is not correct")).to_be_visible()

    page.get_by_label("Setup token").fill(token)
    page.get_by_role("button", name="Create account").click()
    expect(page.get_by_role("heading", name="Sign in")).to_be_visible()

    page.get_by_label("Email").fill("admin@example.com")
    page.get_by_label("Password", exact=True).fill("not the password")
    page.get_by_role("button", name="Sign in").click()
    expect(page.get_by_role("alert").filter(has_text="incorrect")).to_be_visible()

    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Sign in").click()
    nav = page.get_by_role("navigation", name="Locations")
    expect(nav.get_by_role("link")).to_have_count(2)  # My files and the shared tree
    expect(nav.get_by_role("link", name="My files")).to_have_attribute("aria-current", "page")
    page.reload()  # the session survives a reload
    expect(nav).to_be_visible()
    page.get_by_role("button", name="Sign out").click()
    expect(page.get_by_role("heading", name="Sign in")).to_be_visible()
    page.context.close()


def test_folder_crud_matches_real_files(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    expect(page.get_by_text("This folder is empty")).to_be_visible()

    new_folder(page, "Docs")
    new_folder(page, "Archive")
    assert (disk / "Docs").is_dir()

    # a name that already exists is refused with a readable message and the dialog stays open
    page.get_by_role("button", name="New folder").click()
    dialog = page.get_by_role("dialog", name="New folder")
    dialog.get_by_label("Folder name").fill("Docs")
    dialog.get_by_role("button", name="Create").click()
    expect(dialog.get_by_role("alert")).to_have_text("An item with that name already exists here.")
    dialog.get_by_role("button", name="Cancel").click()

    open_folder(page, "Docs")
    payload = os.urandom(3 * 1024 * 1024)
    upload(page, "report.bin", payload)
    expect(row(page, "report.bin")).to_be_visible()
    assert (disk / "Docs" / "report.bin").read_bytes() == payload

    # uploading the same name again is a conflict the user can resolve; nothing is overwritten
    upload(page, "report.bin", b"second")
    uploads = page.get_by_role("list", name="Uploads")
    expect(uploads.get_by_text("already exists")).to_be_visible()
    uploads.get_by_role("button", name="Keep both").click()
    expect(row(page, "report (2).bin")).to_be_visible()
    assert (disk / "Docs" / "report (2).bin").read_bytes() == b"second"
    assert (disk / "Docs" / "report.bin").read_bytes() == payload

    select(page, "report.bin")
    with page.expect_download() as download:
        page.get_by_role("link", name="Download").click()
    assert Path(download.value.path()).read_bytes() == payload

    page.get_by_role("button", name="Rename").click()
    dialog = page.get_by_role("dialog", name="Rename")
    dialog.get_by_label("New name").fill("final.bin")
    dialog.get_by_role("button", name="Rename").click()
    expect(row(page, "final.bin")).to_be_visible()
    assert (disk / "Docs" / "final.bin").read_bytes() == payload
    assert not (disk / "Docs" / "report.bin").exists()

    select(page, "final.bin")
    page.get_by_role("button", name="Copy…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Copy"))
    dialog.get_by_role("button", name="Archive").click()
    dialog.get_by_role("button", name="Copy here").click()
    expect(dialog).to_be_hidden()
    assert (disk / "Archive" / "final.bin").read_bytes() == payload
    assert (disk / "Docs" / "final.bin").read_bytes() == payload

    # moving onto a name that is taken is refused and explained
    select(page, "final.bin")
    page.get_by_role("button", name="Move…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Move"))
    dialog.get_by_role("button", name="Archive").click()
    expect(dialog.get_by_text("Destination: Archive")).to_be_visible()
    dialog.get_by_role("button", name="Move here").click()
    expect(dialog.get_by_role("alert")).to_have_text("An item with that name already exists here.")
    dialog.get_by_role("button", name="Cancel").click()
    assert (disk / "Docs" / "final.bin").exists()
    page.close()


def test_move_between_folders(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    open_folder(page, "Docs")
    select(page, "report (2).bin")
    page.get_by_role("button", name="Move…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Move"))
    dialog.get_by_role("button", name="Archive").click()
    dialog.get_by_role("button", name="Move here").click()
    expect(dialog).to_be_hidden()
    expect(row(page, "report (2).bin")).to_have_count(0)
    assert (disk / "Archive" / "report (2).bin").read_bytes() == b"second"
    assert not (disk / "Docs" / "report (2).bin").exists()

    # uploading over an existing name never overwrites it
    crumbs(page).get_by_role("link", name="My files").click()
    open_folder(page, "Archive")
    upload(page, "final.bin", b"other")
    expect(page.get_by_role("list", name="Uploads").get_by_text("already exists")).to_be_visible()
    assert (disk / "Archive" / "final.bin").stat().st_size == 3 * 1024 * 1024
    page.close()


def test_keyboard_operation(browser: Browser, world: World) -> None:
    page = sign_in(browser, world, world.alice_mail)
    rows = page.locator("tbody tr")
    expect(rows).to_have_count(2)  # Archive, Docs

    # the skip link is the first tab stop
    page.keyboard.press("Tab")
    expect(page.get_by_role("link", name="Skip to files")).to_be_focused()

    rows.first.focus()
    page.keyboard.press("ArrowDown")
    expect(rows.nth(1)).to_be_focused()
    page.keyboard.press("ArrowUp")
    expect(rows.first).to_be_focused()
    page.keyboard.press("End")
    expect(rows.nth(1)).to_be_focused()
    page.keyboard.press("Home")
    page.keyboard.press("Space")
    expect(rows.first).to_have_attribute("aria-selected", "true")

    # F2 renames the focused row; Escape closes the dialog and returns focus to the row
    page.keyboard.press("F2")
    dialog = page.get_by_role("dialog", name="Rename")
    expect(dialog).to_be_visible()
    expect(dialog.get_by_label("New name")).to_be_focused()
    page.keyboard.press("Escape")
    expect(dialog).to_be_hidden()
    expect(rows.first).to_be_focused()

    # Enter opens a folder
    page.keyboard.press("Enter")
    expect(crumbs(page).get_by_text("Archive")).to_be_visible()
    page.close()


def test_phone_sized_viewport(browser: Browser, world: World) -> None:
    w = world
    page = sign_in(browser, w, w.alice_mail, viewport={"width": 375, "height": 812}, has_touch=True)
    nav = page.get_by_role("navigation", name="Locations")
    expect(nav.get_by_role("link", name="My files")).to_be_visible()
    expect(page.get_by_role("button", name="Upload here")).to_be_visible()
    new_folder(page, "Phone")
    assert (w.alice_disk / "Phone").is_dir()
    select(page, "Phone")
    expect(page.get_by_role("button", name="Rename")).to_be_visible()
