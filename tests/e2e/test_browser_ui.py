def test_forbidden_ui_and_direct_api(browser: Browser, world: World) -> None:
    w = world
    denied = "You do not have access to this folder."

    # Bob cannot open Alice's personal folder, and the server refuses direct calls too
    bob = sign_in(browser, w, w.bob_mail)
    bob.goto(f"{w.base}/f/{w.alice_root}")
    expect(bob.get_by_role("alert")).to_have_text(denied)
    for method, path, body in [
        ("GET", f"/api/v1/nodes/{w.alice_root}/children", None),
        ("POST", f"/api/v1/nodes/{w.alice_root}/folders", {"name": "intruder"}),
        ("GET", f"/api/v1/nodes/{w.alice_root}/content", None),
    ]:
        assert api_status(bob, method, path, body) == 403, (method, path)
    assert not (w.alice_disk / "intruder").exists()

    # a web administrator has no personal-folder bypass either
    admin = sign_in(browser, w, "admin@example.com")
    admin.goto(f"{w.base}/f/{w.alice_root}")
    expect(admin.get_by_role("alert")).to_have_text(denied)
    assert api_status(admin, "GET", f"/api/v1/nodes/{w.alice_root}/children") == 403
    admin.close()

    # Alice shares Docs with Bob as a viewer: visible and readable, but every change is disabled
    kids = w.alice.call("GET", f"/api/v1/nodes/{w.alice_root}/children")[1]["items"]
    docs = next(c["id"] for c in kids if c["name"] == "Docs")
    bob_id = user_id(w.stack, w.bob_mail)
    put = w.alice.call("PUT", f"/api/v1/nodes/{docs}/grants/{bob_id}", {"level": "viewer"})
    assert put[0] == 200
    bob.goto(w.base + "/")
    bob.get_by_role("navigation", name="Shared files").get_by_role(
        "link", name="Shared with you"
    ).click()
    link = bob.get_by_role("main").get_by_role("link", name="Docs")
    expect(link).to_be_visible()
    link.click()
    expect(bob.get_by_text("Read-only")).to_be_visible()
    expect(bob.get_by_role("button", name="Upload", exact=True)).to_be_disabled()
    expect(bob.get_by_role("button", name="New folder")).to_be_disabled()
    select(bob, "final.bin")
    expect(bob.get_by_role("link", name="Download")).to_be_visible()  # viewers may read
    expect(bob.get_by_role("button", name="Rename")).to_be_disabled()
    expect(bob.get_by_role("button", name="Move…")).to_be_disabled()
    expect(bob.get_by_role("button", name="Copy…")).to_be_disabled()

    file_id = next(
        c["id"]
        for c in w.alice.call("GET", f"/api/v1/nodes/{docs}/children")[1]["items"]
        if c["name"] == "final.bin"
    )
    assert api_status(bob, "POST", f"/api/v1/nodes/{docs}/folders", {"name": "nope"}) == 403
    rename = {"name": "x", "expected_revision": 1}
    assert api_status(bob, "POST", f"/api/v1/nodes/{file_id}/rename", rename) == 403
    assert api_status(bob, "GET", f"/api/v1/nodes/{file_id}/content") == 200
    assert (w.alice_disk / "Docs" / "final.bin").exists()
    assert not (w.alice_disk / "Docs" / "nope").exists()

    # revoking the grant takes effect on the next request
    assert w.alice.call("DELETE", f"/api/v1/nodes/{docs}/grants/{bob_id}")[0] == 200
    assert api_status(bob, "GET", f"/api/v1/nodes/{docs}/children") == 403
    bob.close()


def test_first_run_server_steps_run_in_order(fresh_stack: Stack, browser: Browser) -> None:
    # The administrator's first-run server step runs in a fixed order (AI, account, users, mail),
    # the users and mail screens open inside it and return to it, and only then the file setup.
    stack = fresh_stack
    base = f"http://127.0.0.1:{stack.port}"
    page = browser.new_context().new_page()
    page.goto(base + "/")
    expect(page.get_by_role("heading", name="Create the administrator")).to_be_visible()
    logs = stack.compose("logs", "--no-color", "api").stdout
    token = re.findall(r"FIRST-RUN SETUP TOKEN[^:]*: ([\w-]+)", logs)[-1]
    page.get_by_label("Setup token").fill(token)
    page.get_by_label("Your name").fill("Ada")
    page.get_by_label("Email").fill("admin@example.com")
    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Create account").click()
    expect(page.get_by_role("heading", name="Sign in")).to_be_visible()
    page.get_by_label("Email").fill("admin@example.com")
    page.get_by_label("Password", exact=True).fill(PASSWORD)
    page.get_by_role("button", name="Sign in").click()

    expect(page.get_by_role("heading", level=1, name="Prepare your server")).to_be_visible()
    expect(page.locator("ol.setup-steps > li > strong")).to_have_text(
        [
            "Step 1: AI",
            "Step 2: Meaning-based search (optional)",
            "Step 3: Mail server (optional)",
            "Step 4: Other users (optional)",
            "Step 5: Server files",
        ]
    )
    # Step 1 is already open beside the list when setup starts
    expect(page.get_by_role("region", name="Step 1: AI")).to_be_visible()
    # Every step opens beside the step list (two panes), never instead of it
    for button, title in [
        ("Choose AI settings", "Step 1: AI"),
        ("Set up meaning-based search", "Step 2: Meaning-based search"),
        ("Set up mail server", "Step 3: Mail server"),
        ("Invite users", "Step 4: Other users"),
        ("Set up server files", "Step 5: Server files"),
    ]:
        page.get_by_role("button", name=button).click()
        panel = page.get_by_role("region", name=title)
        expect(panel).to_be_visible()
        expect(page.get_by_role("dialog")).to_have_count(0)
        expect(page.locator("ol.setup-steps")).to_be_visible()
        steps_box = page.locator("ol.setup-steps").bounding_box()
        panel_box = panel.bounding_box()
        assert steps_box and panel_box and steps_box["x"] < panel_box["x"]
        # A wide layout: steps a third, panel two thirds, across most of the window
        assert 1.8 < panel_box["width"] / steps_box["width"] < 2.2
        span = panel_box["x"] + panel_box["width"] - steps_box["x"]
        assert span > 0.85 * page.viewport_size["width"]
        if button == "Set up mail server":
            expect(panel.get_by_label("Mail server")).to_be_visible()
            expect(panel.get_by_role("button", name="Send a test message")).to_be_visible()
            expect(panel.get_by_label("Enable incoming mail")).to_be_visible()
        if button == "Invite users":
            # the invite form is a popup opened from a button above the table, not a section
            expect(panel.get_by_text("Invite someone")).to_have_count(0)
            expect(panel.get_by_role("table", name="Accounts")).to_be_visible()
            panel.get_by_role("button", name="Invite user", exact=True).click()
            popup = page.get_by_role("dialog", name="Invite user")
            expect(popup.get_by_role("button", name="Create invitation")).to_be_visible()
            popup.get_by_role("button", name="Close", exact=True).click()
            expect(page.get_by_role("dialog")).to_have_count(0)
        panel.get_by_role("button", name="Close", exact=True).first.click()
        expect(panel).to_have_count(0)
        expect(page.get_by_role("heading", level=1, name="Prepare your server")).to_be_visible()
        expect(page.get_by_text("Choose a step to set it up here.")).to_be_visible()
    expect(page.get_by_role("button", name="Continue to file setup")).to_have_count(0)
    page.get_by_role("button", name="Set up server files").click()
    expect(page.get_by_role("region", name="Set up Server files")).to_be_visible()
