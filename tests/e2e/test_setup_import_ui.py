@dataclass
class Person:
    mail: str
    client: Client
    uid: str
    root: str
    disk: Path


def new_person(w: BaseWorld, name: str) -> Person:
    admin = Client(w.stack)
    assert admin.login("admin@example.com") == 200
    mail = f"{name}{uuid.uuid4().hex[:6]}@example.com"
    client = invite_and_login(w.stack, admin, mail)
    uid = user_id(w.stack, mail)
    return Person(
        mail, client, uid, root_node(w.stack, f"personal/{uid}"), w.stack.library / "personal" / uid
    )


def make_tree(base: Path, files: dict[str, bytes], dirs: tuple[str, ...] = ()) -> Path:
    for rel, data in files.items():
        target = base / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    for rel in dirs:
        (base / rel).mkdir(parents=True, exist_ok=True)
    return base


def on_disk(root: Path) -> dict[str, bytes]:
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in sorted(root.rglob("*"))
        if p.is_file()
    }


def wait_until(page: Page, check: Any, timeout: float = 90, reload: bool = True) -> None:
    """Polls a condition on the page (a background scan has no UI signal to wait for)."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if reload:
            page.reload()
            page.wait_for_load_state("networkidle")  # the list is fetched after the page loads
        if check():
            return
        time.sleep(1.5)
    raise AssertionError("condition never became true")


