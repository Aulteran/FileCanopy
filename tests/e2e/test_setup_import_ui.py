def test_interrupted_import_is_resumed_by_selecting_the_folder_again(
    browser: Browser, world: BaseWorld, tmp_path: Path
) -> None:
    w = world
    p = new_person(w, "rhea")
    files = {f"Album/p{i:02d}.bin": os.urandom(800 + i) for i in range(8)}
    src = make_tree(tmp_path / "Album", {k.split("/", 1)[1]: v for k, v in files.items()})
    manifest = []
    for i, (k, v) in enumerate(files.items()):
        name = k.split("/", 1)[1]
        stamp = 1_700_000_000 + i  # whole seconds: the page and this test agree to the millisecond
        os.utime(src / name, (stamp, stamp))
        manifest.append({"path": name, "kind": "file", "size": len(v), "mtime": stamp * 1000})
    # a first session got through three files and then the connection was lost
    status, batch, _ = p.client.call(
        "POST", f"/api/v1/nodes/{p.root}/setup/import", {"entries": manifest}
    )
    assert status == 201, batch
    assert p.client.call("POST", f"/api/v1/imports/{batch['id']}/start")[0] == 200
    pending = p.client.call(
        "GET", f"/api/v1/imports/{batch['id']}/entries?status=pending&limit=500"
    )[1]
    for entry in pending["items"][:3]:
        status, out, _ = raw(
            p.client,
            "PUT",
            f"/api/v1/imports/{batch['id']}/entries/{entry['index']}",
            (src / entry["path"]).read_bytes(),
            **{"Content-Type": "application/octet-stream"},
        )
        assert status == 200, out
    assert len(on_disk(p.disk)) == 3

    page = sign_in(browser, w, p.mail, setup=True)
    panel = page.get_by_role("region", name="Set up My files")
    report = panel.get_by_label("Import report")
    expect(report).to_contain_text("Import not finished")
    expect(report).to_contain_text("3 files copied")
    expect(report).to_contain_text("5 still to do")
    page.get_by_test_id("resume-folder-input").set_input_files(str(src))
    expect(report).to_contain_text("Import finished")
    expect(report).to_contain_text("8 files copied")
    got = on_disk(p.disk)
    assert sorted(got) == sorted(k.split("/", 1)[1] for k in files)  # each file exactly once
    for k, v in files.items():
        assert got[k.split("/", 1)[1]] == v
    page.close()


def test_missing_unsupported_collision_and_suspended_states(
    browser: Browser, world: BaseWorld
) -> None:
    w = world
    p = new_person(w, "kai")
    stack = w.stack
    c = p.client

    def mkdir(parent: str, name: str) -> str:
        status, out, _ = c.call("POST", f"/api/v1/nodes/{parent}/folders", {"name": name})
        assert status == 201, out
        return str(out["node"]["id"])

    gone = mkdir(p.root, "Gone")
    bulk = mkdir(p.root, "Bulk")  # this also closes the setup window
    for name in ("keep.txt", "vanish.txt"):
        status, out, _ = raw(
            c,
            "POST",
            f"/api/v1/nodes/{gone}/files?name={name}",
            name.encode(),
            **{"Content-Type": "application/octet-stream"},
        )
        assert status == 201, out

    # greyed-out and name-collision entries as the reconciler records them (ADR-011 section 9):
    # symlinks, special files and case-twins cannot be made portably on a Windows bind mount
    # (the reconciler producing them is covered by the M06a tests on real files), so the rows
    # are written directly and only the display is tested here
    now = "now()"
    for name, kind, reason in [
        ("shortcut", "other", "symlink"),
        ("external-drive", "other", "mounted_drive"),
        ("pipe", "other", "special"),
    ]:
        nid = uuid.uuid4()
        stack.sql(
            "insert into node (id, root_id, parent_id, name, name_key, kind, lineage, status, "
            "revision, unsupported_reason, created_at, updated_at) "
            f"select '{nid}', root_id, id, '{name}', '{name}', '{kind}', "
            f"lineage || '{nid}/', 'active', 1, '{reason}', {now}, {now} from node "
            f"where id = '{p.root}'"
        )
    for nid, name in [(uuid.uuid4(), "Report.pdf"), (uuid.uuid4(), "report.pdf")]:
        stack.sql(
            "insert into node (id, root_id, parent_id, name, name_key, kind, lineage, status, "
            "revision, size, created_at, updated_at) "
            f"select '{nid}', root_id, id, '{name}', 'report.pdf', 'file', "
            f"lineage || '{nid}/', 'active', 1, 4, {now}, {now} from node where id = '{p.root}'"
        )

    page = sign_in(browser, w, p.mail)
    expect(row(page, "shortcut")).to_contain_text("not supported: symbolic link")
    expect(row(page, "external-drive")).to_contain_text("not supported: mounted drive")
    expect(row(page, "pipe")).to_contain_text("not supported: special file")
    expect(row(page, "shortcut")).to_have_class(re.compile("unsupported"))  # greyed out
    expect(row(page, "shortcut").get_by_role("link")).to_have_count(0)  # never opened
    select(page, "shortcut")
    expect(page.get_by_text("never opens or changes it")).to_be_visible()
    for name in ("Rename", "Move…", "Copy…"):
        expect(page.get_by_role("button", name=name)).to_have_count(0)
    expect(page.get_by_role("link", name="Download")).to_have_count(0)
    twins = page.get_by_role("row").filter(has_text="differs only by case")
    expect(twins).to_have_count(2)

    # a file removed on the host is shown as missing, never as deleted; it can be dismissed
    open_gone = row(page, "Gone").get_by_role("link", name="Gone")
    open_gone.click()
    expect(row(page, "vanish.txt")).to_be_visible()
    (stack.library / "personal" / p.uid / "Gone" / "vanish.txt").unlink()
    page.get_by_role("button", name="Rescan").first.click()
    wait_until(
        page,
        lambda: (
            row(page, "vanish.txt").count() > 0
            and "missing" in row(page, "vanish.txt").inner_text()
        ),
    )
    expect(row(page, "vanish.txt")).to_contain_text("missing, rescan needed")
    expect(row(page, "keep.txt")).not_to_contain_text("missing")
    select(page, "vanish.txt")
    expect(page.get_by_text("Nothing was deleted here")).to_be_visible()
    expect(page.get_by_role("link", name="Download")).to_have_count(0)
    page.get_by_role("button", name="Remove from list").click()
    expect(row(page, "vanish.txt")).to_have_count(0)
    assert (stack.library / "personal" / p.uid / "Gone" / "keep.txt").exists()

    # a mass disappearance suspends the root instead of marking everything missing
    bulk_dir = stack.library / "personal" / p.uid / "Bulk"
    for i in range(130):
        (bulk_dir / f"f{i:03d}.txt").write_bytes(b"x")
    page.goto(f"{w.base}/f/{bulk}")
