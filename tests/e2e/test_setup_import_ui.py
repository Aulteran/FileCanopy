    assert got == {
        "a.txt": b"alpha",
        "b.txt": b"beta",
        "c.txt": b"gamma",
        "inner/d.txt": b"delta",
    }
    assert (p.disk / "inner" / "hollow").is_dir()  # empty folders survive a drop
    panel.get_by_role("button", name="Finish setup").click()
    expect(panel).to_have_count(0)
    expect(row(page, "a.txt")).to_be_visible()  # the browser, with the imported files

    # after setup a dropped folder is an ordinary folder upload: its name is kept, folders merge,
    # and a file whose name is taken is kept next to the existing one
    fake_directory_drop(page, ".browser")
    jobs = page.get_by_role("list", name="Folder uploads")
    expect(jobs).to_contain_text("Dropped")
    expect(jobs).to_contain_text("Done, 4 files")
    expect(row(page, "Dropped")).to_be_visible()
    got = on_disk(p.disk)
    assert got["Dropped/a.txt"] == b"alpha" and got["Dropped/inner/d.txt"] == b"delta"
    fake_directory_drop(page, ".browser")
    expect(jobs).to_contain_text("kept next to a file with the same name")
    assert on_disk(p.disk)["Dropped/a (2).txt"] == b"alpha"
    assert sorted(x.name for x in p.disk.iterdir()) == [
        "Dropped",
        "a.txt",
        "b.txt",
        "c.txt",
        "inner",
    ]
    page.close()


