"""M06d in a real browser against the real stack: the account screens, upload byte progress and
the move/copy picker past one page of folders.

Covers an administrator inviting someone on the Users page and handing over the one-time link,
the invited person setting a password on /invite and signing in, the link refusing a second use,
a password reset link that ends the person's sessions, a member being refused the page and the
admin API, the one-time secret staying out of the address bar and the server's access log, upload
progress in bytes with a working Cancel (no file left on disk), and the picker listing every
subfolder of a folder with more than one page of entries. Random credentials and generated bytes
only.
"""

import os
import re
import uuid

import pytest
from playwright.sync_api import Browser, Page, expect
from support import World, api_status, open_folder, row, select, sign_in, upload
from test_auth_stack import PASSWORD, Client
from test_storage_stack import invite_and_login, root_node, setup_admin, user_id

pytestmark = pytest.mark.e2e

NEW_PASSWORD = "plum orchard lantern 42"


def _issued_link(page: Page, what: str) -> str:
    panel = page.get_by_role("region", name=re.compile(f"^{what} for "))
    expect(panel).to_be_visible()
    link = panel.get_by_label("Link").input_value()
    panel.get_by_role("button", name="Done").click()
    expect(panel).to_be_hidden()
    return link


def _set_password(browser: Browser, link: str, password: str, *, name: str | None = None) -> Page:
    page = browser.new_context().new_page()
    page.goto(link)
    # the secret is taken out of the address bar as soon as the page loads
    expect(page.get_by_label("New password", exact=True)).to_be_visible()
    assert "#" not in page.url and "token" not in page.url
    if name is not None:
        page.get_by_label("Your name (optional)").fill(name)
    page.get_by_label("New password", exact=True).fill(password)
    page.get_by_label("Repeat the password").fill(password)
    return page


def test_invite_accept_and_reset_through_the_ui(world: World, browser: Browser) -> None:
    email = f"carol{uuid.uuid4().hex[:6]}@example.com"
    admin = sign_in(browser, world, "admin@example.com")
    admin.get_by_role("link", name="Users").click()
    expect(admin.get_by_role("heading", name="Users", exact=True)).to_be_visible()

    invite = admin.get_by_role("region", name="Invite someone")
    invite.get_by_label("Email").fill(email)
    invite.get_by_label("Name").fill("Carol")
    invite.get_by_role("button", name="Create invitation").click()
    link = _issued_link(admin, "Invitation link")
    assert re.fullmatch(rf"{re.escape(world.base)}/invite#token=[\w%-]+", link), link
    accounts = admin.get_by_role("table", name="Accounts")
    expect(row(admin, email)).to_contain_text("Invited")

    # mismatched passwords are caught before anything is sent; then the invitation is accepted
    page = _set_password(browser, link, PASSWORD, name="Carol C")
    page.get_by_label("Repeat the password").fill(PASSWORD + "x")
    page.get_by_role("button", name="Set password").click()
    expect(page.get_by_role("alert")).to_have_text("The two passwords are not the same.")
    page.get_by_label("Repeat the password").fill(PASSWORD)
    page.get_by_role("button", name="Set password").click()
    expect(page.get_by_role("heading", name="Your account is ready")).to_be_visible()
    page.get_by_role("link", name="Go to sign in").click()
    expect(page.get_by_role("button", name="Sign in")).to_be_visible()

    # the same link works once only
    again = _set_password(browser, link, PASSWORD)
    again.get_by_role("button", name="Set password").click()
    expect(again.get_by_role("alert")).to_contain_text("not valid any more")

    # signed in: the new account works, is a member and sees no Users link
    carol = sign_in(browser, world, email)
    expect(carol.get_by_role("link", name="Users")).to_have_count(0)
    admin.reload()
    expect(row(admin, email)).to_contain_text("Active")
    expect(row(admin, "Carol C")).to_be_visible()

    # a reset link ends the person's sessions once used; the old password stops working
    admin.get_by_role("button", name=f"Password reset link for {email}").click()
    reset = _issued_link(admin, "Password reset link")
    assert "/reset#token=" in reset
    page = _set_password(browser, reset, NEW_PASSWORD)
    page.get_by_role("button", name="Change password").click()
    expect(page.get_by_role("heading", name="Your password was changed")).to_be_visible()
    assert api_status(carol, "GET", "/api/v1/roots") == 401
    assert Client(world.stack).login(email) == 401
    assert Client(world.stack).login(email, NEW_PASSWORD) == 200

    # administration from the page: disable and enable; the administrator cannot disable themself
    admin.get_by_role("button", name=f"Disable {email}").click()
    expect(row(admin, email)).to_contain_text("Disabled")
    assert Client(world.stack).login(email, NEW_PASSWORD) == 401
    admin.get_by_role("button", name=f"Enable {email}").click()
    expect(row(admin, email)).to_contain_text("Active")
    expect(accounts.get_by_role("button", name="Disable admin@example.com")).to_have_count(0)

    # the one-time secrets never reached the server: nginx logs show the path only
    logs = world.stack.compose("logs", "--no-color", "web", "api").stdout
    for secret in (link, reset):
        assert secret.split("#token=", 1)[1] not in logs


def test_a_broken_link_explains_itself(world: World, browser: Browser) -> None:
    page = browser.new_context().new_page()
    page.goto(world.base + "/invite")
    expect(page.get_by_role("alert")).to_contain_text("This link is incomplete")
    page.goto(world.base + "/reset#token=not-a-real-token")
    page.get_by_label("New password", exact=True).fill(NEW_PASSWORD)
    page.get_by_label("Repeat the password").fill(NEW_PASSWORD)
    page.get_by_role("button", name="Change password").click()
    expect(page.get_by_role("alert")).to_contain_text("not valid any more")


def test_member_cannot_manage_users(world: World, browser: Browser) -> None:
    page = sign_in(browser, world, world.alice_mail)
    expect(page.get_by_role("link", name="Users")).to_have_count(0)
    page.goto(world.base + "/admin/users")
    expect(page.get_by_text("Only administrators can manage users.")).to_be_visible()
    assert api_status(page, "GET", "/api/v1/admin/users") == 403
    body = {"email": "x@example.com", "name": "X", "role": "admin"}
    assert api_status(page, "POST", "/api/v1/admin/users", body) == 403


def _throttle_uploads(page: Page, bytes_per_second: int) -> None:
    cdp = page.context.new_cdp_session(page)
    cdp.send("Network.enable")
    cdp.send(
        "Network.emulateNetworkConditions",
        {
            "offline": False,
            "latency": 0,
            "downloadThroughput": -1,
            "uploadThroughput": bytes_per_second,
        },
    )


def test_upload_shows_bytes_and_can_be_cancelled(world: World, browser: Browser) -> None:
    w = world
    page = sign_in(browser, w, w.alice_mail)
    _throttle_uploads(page, 512 * 1024)
    uploads = page.get_by_role("list", name="Uploads")

    upload(page, "progress.bin", os.urandom(2 * 1024 * 1024))
    bar = page.get_by_role("progressbar", name="Upload progress of progress.bin")
    expect(bar).to_be_visible()
    expect(uploads).to_contain_text(re.compile(r"of 2\.0 MB \(\d+%\)"))
    expect(uploads).to_contain_text("Done", timeout=30_000)
    expect(bar).to_be_hidden()
    assert (w.alice_disk / "progress.bin").stat().st_size == 2 * 1024 * 1024

    upload(page, "cancelled.bin", os.urandom(4 * 1024 * 1024))
    page.get_by_role("button", name="Cancel upload of cancelled.bin").click()
    expect(uploads).to_contain_text("Upload cancelled.")
    expect(row(page, "cancelled.bin")).to_have_count(0)
    assert not (w.alice_disk / "cancelled.bin").exists()
    leftovers = [p.name for p in w.alice_disk.iterdir() if "cancelled" in p.name]
    assert leftovers == []


def test_picker_offers_folders_past_the_first_page(world: World, browser: Browser) -> None:
    stack = world.stack
    email = f"dave{uuid.uuid4().hex[:6]}@example.com"
    dave = invite_and_login(stack, setup_admin(stack), email)
    root = root_node(stack, f"personal/{user_id(stack, email)}")
    status, many, _ = dave.call("POST", f"/api/v1/nodes/{root}/folders", {"name": "Many"})
    assert status == 201
    many_id = many["node"]["id"]
    for i in range(230):
        assert dave.call("POST", f"/api/v1/nodes/{many_id}/folders", {"name": f"f{i:03}"})[0] == 201
    page = sign_in(browser, world, email)
    upload(page, "item.txt", b"move me")
    expect(row(page, "item.txt")).to_be_visible()
    select(page, "item.txt")
    page.get_by_role("button", name="Move…").click()
    dialog = page.get_by_role("dialog", name=re.compile("Move"))
    dialog.get_by_role("button", name="Many", exact=True).click()
    expect(dialog.get_by_text("Destination: Many")).to_be_visible()
    folders = dialog.get_by_role("list", name="Folders").get_by_role(
        "button", name=re.compile(r"^f\d{3}$")
    )
    expect(folders).not_to_have_count(0)
    assert folders.count() < 230  # one page only, until asked for more
    dialog.get_by_role("button", name="Show more folders").click()
    expect(folders).to_have_count(230)
    expect(dialog.get_by_role("button", name="Show more folders")).to_have_count(0)
    # every folder is reachable, including those from the second page
    for name in ("f000", "f229"):
        expect(dialog.get_by_role("button", name=name, exact=True)).to_be_visible()
    dialog.get_by_role("button", name="f229", exact=True).click()
    expect(dialog.get_by_text("Destination: f229")).to_be_visible()
    dialog.get_by_role("button", name="Move here").click()
    expect(dialog).to_be_hidden()
    expect(row(page, "item.txt")).to_have_count(0)
    open_folder(page, "Many")
    page.get_by_role("button", name="Load more").click()
    open_folder(page, "f229")
    expect(row(page, "item.txt")).to_be_visible()
