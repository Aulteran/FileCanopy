def toast(page: Page):  # type: ignore[no-untyped-def]
    return page.locator(".toast")


def open_trash(page: Page) -> None:
    page.get_by_role("navigation", name="Trash and history").get_by_role(
        "link", name="Trash"
    ).click()
    expect(page.get_by_role("heading", name="Trash", exact=True)).to_be_visible()


def trash_row(page: Page, name: str):  # type: ignore[no-untyped-def]
    return (
        page.get_by_role("list", name="Items in the Trash")
        .get_by_role("listitem")
        .filter(has_text=name)
    )


def delete_selected(page: Page, name: str) -> None:
    select(page, name)
    page.get_by_role("button", name="Delete", exact=True).click()
    expect(toast(page)).to_contain_text(f"Moved {name} to the Trash")


def test_delete_goes_to_trash_and_restores(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    new_folder(page, "T7a")
    open_folder(page, "T7a")
    data = os.urandom(2048)
    upload(page, "gone.txt", data)
    expect(row(page, "gone.txt")).to_be_visible()
    delete_selected(page, "gone.txt")
    expect(row(page, "gone.txt")).to_have_count(0)
    assert not (disk / "T7a" / "gone.txt").exists()

    open_trash(page)
    item = trash_row(page, "gone.txt")
    expect(item).to_be_visible()
    expect(item).to_contain_text("days left")
    expect(item).to_contain_text("from T7a")
    item.get_by_role("button", name="Restore gone.txt", exact=True).click()
    expect(page.get_by_role("status").filter(has_text="Restored gone.txt.")).to_be_visible()
    expect(trash_row(page, "gone.txt")).to_have_count(0)
    assert (disk / "T7a" / "gone.txt").read_bytes() == data

    # delete forever asks first, and then really removes it
    page.get_by_role("navigation", name="Locations").get_by_role("link", name="My files").click()
    open_folder(page, "T7a")
    delete_selected(page, "gone.txt")
    open_trash(page)
    trash_row(page, "gone.txt").get_by_role("button", name="Delete gone.txt forever").click()
    dialog = page.get_by_role("dialog", name="Delete forever?")
    dialog.get_by_role("button", name="Cancel").click()
    expect(trash_row(page, "gone.txt")).to_be_visible()
    trash_row(page, "gone.txt").get_by_role("button", name="Delete gone.txt forever").click()
    page.get_by_role("dialog", name="Delete forever?").get_by_role(
        "button", name="Delete forever"
    ).click()
    expect(trash_row(page, "gone.txt")).to_have_count(0)
    page.close()


def test_undo_rename_and_the_refusal_after_a_host_edit(browser: Browser, world: World) -> None:
    w, disk = world, world.alice_disk
    page = sign_in(browser, w, w.alice_mail)
    new_folder(page, "T7b")
    open_folder(page, "T7b")
    upload(page, "first.txt", b"one")
    expect(row(page, "first.txt")).to_be_visible()

    select(page, "first.txt")
    page.get_by_role("button", name="Rename", exact=True).click()
    dialog = page.get_by_role("dialog", name="Rename")
    dialog.get_by_label("New name").fill("second.txt")
    dialog.get_by_role("button", name="Rename").click()
    expect(row(page, "second.txt")).to_be_visible()
    toast(page).get_by_role("button", name="Undo").click()
    expect(row(page, "first.txt")).to_be_visible()
    assert (disk / "T7b" / "first.txt").read_bytes() == b"one"
    assert not (disk / "T7b" / "second.txt").exists()

    # rename again, then someone edits the file outside the app: undo is refused and says why
    select(page, "first.txt")
    page.get_by_role("button", name="Rename", exact=True).click()
    dialog = page.get_by_role("dialog", name="Rename")
    dialog.get_by_label("New name").fill("third.txt")
    dialog.get_by_role("button", name="Rename").click()
    expect(row(page, "third.txt")).to_be_visible()
    edited = disk / "T7b" / "third.txt"
    edited.write_bytes(b"edited on the host, now longer")
    now = time.time() + 5
    os.utime(edited, (now, now))
    toast(page).get_by_role("button", name="Undo").click()
    expect(page.get_by_role("alert").filter(has_text="Nothing was changed")).to_be_visible()
    assert edited.read_bytes() == b"edited on the host, now longer"
    assert not (disk / "T7b" / "first.txt").exists()
    page.close()


