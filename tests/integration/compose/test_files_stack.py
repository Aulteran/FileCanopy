pytestmark = pytest.mark.compose


@pytest.fixture
def stack(app_stack: Stack) -> Stack:
    return app_stack


def raw(
    c: Client,
    method: str,
    path: str,
    data: bytes | None = None,
    **headers: str,
) -> tuple[int, bytes, Any]:
    hdrs = dict(headers)
    if c.cookie:
        hdrs["Cookie"] = c.cookie
    if c.csrf and method != "GET":
        hdrs["X-CSRF-Token"] = c.csrf
    req = urllib.request.Request(c.base + path, data=data, method=method, headers=hdrs)  # noqa: S310
    try:
        with urllib.request.urlopen(req, timeout=120) as r:  # noqa: S310
            return r.status, r.read(), r.headers
    except urllib.error.HTTPError as e:
        return e.code, e.read(), e.headers


def js(c: Client, method: str, path: str, body: dict[str, Any] | None = None, **h: str) -> Any:
    status, out, _ = c.call(method, path, body, **h)
    return status, out


def test_file_operations_through_nginx_on_postgres(stack: Stack) -> None:
    assert stack.sql("select version_num from alembic_version") == "0009"
    assert stack.sql(
        "select count(*) from information_schema.columns "
        "where table_name = 'node' and column_name in ('revision', 'size')"
    ) == ("2")
    # root statuses such as unsupported_mount (17 characters) must fit the column
    assert (
        int(
            stack.sql(
                "select character_maximum_length from information_schema.columns "
                "where table_name = 'storage_root' and column_name = 'status'"
            )
        )
        >= 24
    )
    stack.sql(
        "begin; update storage_root set status = 'unsupported_mount' "
        "where id = (select id from storage_root limit 1); rollback"
    )
    admin = setup_admin(stack)
    tag = uuid.uuid4().hex[:6]
    alice_mail, bob_mail = f"alice{tag}@example.com", f"bob{tag}@example.com"
    alice = invite_and_login(stack, admin, alice_mail)
    bob = invite_and_login(stack, admin, bob_mail)
    root = root_node(stack, f"personal/{user_id(stack, alice_mail)}")

    # create folders, upload 5 MiB (nginx's old limit was 1 MiB), download, compare
    status, docs = js(alice, "POST", f"/api/v1/nodes/{root}/folders", {"name": "Docs"})
    assert status == 201, docs
    docs_id = docs["node"]["id"]
    payload = os.urandom(5 * 1024 * 1024)
    status, body, _ = raw(
        alice,
        "POST",
        f"/api/v1/nodes/{docs_id}/files?name=big.bin",
        payload,
        **{"Content-Type": "application/octet-stream", "Idempotency-Key": f"up-{tag}"},
    )
    assert status == 201, body
    file_id = json.loads(body)["node"]["id"]
    on_disk = stack.library / "personal" / user_id(stack, alice_mail) / "Docs" / "big.bin"
    assert on_disk.read_bytes() == payload  # an ordinary file on the host bind mount
    status, got, headers = raw(alice, "GET", f"/api/v1/nodes/{file_id}/content")
    assert status == 200 and hashlib.sha256(got).digest() == hashlib.sha256(payload).digest()
    assert headers["Content-Type"] == "application/octet-stream"
    # replay of the same keyed upload creates nothing new
    status, again, _ = raw(
        alice,
        "POST",
        f"/api/v1/nodes/{docs_id}/files?name=big.bin",
        payload,
        **{"Content-Type": "application/octet-stream", "Idempotency-Key": f"up-{tag}"},
    )
    assert status == 201 and json.loads(again)["replayed"] is True
    assert stack.sql(f"select count(*) from node where parent_id = '{docs_id}'") == "1"

    # conflicts never overwrite
    status, body, _ = raw(alice, "POST", f"/api/v1/nodes/{docs_id}/files?name=big.bin", b"x")
    assert status == 409 and json.loads(body)["detail"]["code"] == "NAME_CONFLICT"
    assert on_disk.read_bytes() == payload

    # move a folder tree: PostgreSQL rewrites descendant lineages in the same transaction
    status, other = js(alice, "POST", f"/api/v1/nodes/{root}/folders", {"name": "Archive"})
    status, moved = js(
        alice,
        "POST",
        f"/api/v1/nodes/{docs_id}/move",
        {"target_parent_id": other["node"]["id"], "expected_revision": 1},
    )
    assert status == 200, moved
    lineage = stack.sql(f"select lineage from node where id = '{file_id}'")
    arch_lineage = stack.sql(f"select lineage from node where id = '{other['node']['id']}'")
    assert lineage == f"{arch_lineage}{docs_id}/{file_id}/"
    moved_file = stack.library / "personal" / user_id(stack, alice_mail) / "Archive" / "Docs"
    assert (moved_file / "big.bin").read_bytes() == payload

    # copy gives independent real files and new ids
    status, copy = js(
        alice,
        "POST",
        f"/api/v1/nodes/{docs_id}/copy",
        {"target_parent_id": root, "name": "Docs copy"},
    )
    assert status == 201, copy
    assert (
        stack.library / "personal" / user_id(stack, alice_mail) / "Docs copy" / "big.bin"
    ).read_bytes() == payload

    # authorization through nginx: bob (no grant) and the admin get the uniform 403
    uniform = (403, {"detail": {"code": "FORBIDDEN"}})
    assert js(bob, "GET", f"/api/v1/nodes/{file_id}/content") == uniform or (
        raw(bob, "GET", f"/api/v1/nodes/{file_id}/content")[0] == 403
    )
    assert js(bob, "GET", f"/api/v1/nodes/{root}/children") == uniform
    assert raw(admin, "GET", f"/api/v1/nodes/{file_id}/content")[0] == 403
    assert js(bob, "POST", f"/api/v1/nodes/{root}/folders", {"name": "x"}) == uniform

    # real concurrency: two renames with the same revision, exactly one wins
    status, f = js(alice, "POST", f"/api/v1/nodes/{root}/folders", {"name": "Race"})
    race_id = f["node"]["id"]
    results: list[int] = []

    def rename(name: str) -> None:
        c = Client(stack)
        c.cookie, c.csrf = alice.cookie, alice.csrf
        body = {"name": name, "expected_revision": 1}
        results.append(js(c, "POST", f"/api/v1/nodes/{race_id}/rename", body)[0])

    threads = [threading.Thread(target=rename, args=(f"Race-{i}",)) for i in range(4)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    assert sorted(results) == [200, 409, 409, 409], results
    assert stack.sql(f"select revision from node where id = '{race_id}'") == "2"
    names = [p.name for p in (stack.library / "personal" / user_id(stack, alice_mail)).iterdir()]
    assert sum(n.startswith("Race") for n in names) == 1

    # journal rows are in PostgreSQL; nothing is left half-done; no staging files remain
    assert stack.sql("select count(*) from file_operation where status = 'planned'") == "0"
    # (only this test's own users: another suite may have trashed or purged nodes of its own)
    mine = f"'{user_id(stack, alice_mail)}', '{user_id(stack, bob_mail)}'"
    assert (
        stack.sql(
            "select count(*) from node n join storage_root r on r.id = n.root_id "
            f"where n.status <> 'active' and r.owner_user_id in ({mine})"
        )
        == "0"
    )
    leftovers = [p for p in stack.library.rglob(".filecanopy-tmp-*")]
    assert leftovers == []


def test_outside_changes_are_reconciled_on_postgres(stack: Stack) -> None:
    """M06a: a rename and a new file made on the host bind mount are picked up by "rescan now"
    (the real reconciler thread, PostgreSQL advisory locks and lineage rewrite), a vanished file
    becomes missing rather than deleted, and the external actor never names a user."""
    admin = setup_admin(stack)
    tag = uuid.uuid4().hex[:6]
    mail = f"carol{tag}@example.com"
    carol = invite_and_login(stack, admin, mail)
    uid = user_id(stack, mail)
    root = root_node(stack, f"personal/{uid}")
    status, docs = js(carol, "POST", f"/api/v1/nodes/{root}/folders", {"name": "Docs"})
    assert status == 201, docs
    docs_id = docs["node"]["id"]
    status, body, _ = raw(
        carol,
        "POST",
        f"/api/v1/nodes/{docs_id}/files?name=old.txt",
        b"outside change",
        **{"Content-Type": "application/octet-stream"},
    )
    assert status == 201, body
    file_id = json.loads(body)["node"]["id"]
    gone_status, gone_body, _ = raw(
        carol,
        "POST",
        f"/api/v1/nodes/{docs_id}/files?name=doomed.txt",
        b"will vanish",
        **{"Content-Type": "application/octet-stream"},
    )
    assert gone_status == 201, gone_body
    doomed_id = json.loads(gone_body)["node"]["id"]

    folder = stack.library / "personal" / uid / "Docs"
    # created before the unlink: a freed inode number is often reused at once, and ADR-011 reads a
    # reused inode as an uncertain inferred move rather than a deletion
    (folder / "from-host.txt").write_bytes(b"hello from the host")
    (folder / "old.txt").rename(folder / "renamed.txt")
    (folder / "doomed.txt").unlink()

    status, queued = js(carol, "POST", f"/api/v1/nodes/{docs_id}/rescan")
    assert status == 202, queued
    deadline = time.monotonic() + 60
    names: dict[str, str] = {}
    while time.monotonic() < deadline:
        status, listing = js(carol, "GET", f"/api/v1/nodes/{docs_id}/children")
        names = {i["name"]: i["id"] for i in listing["items"]}
        if (
            "renamed.txt" in names
            and "from-host.txt" in names
            and stack.sql(f"select status from node where id = '{doomed_id}'") == "missing"
        ):
            break
        time.sleep(1)
    assert names.get("renamed.txt") == file_id  # same identity after an outside rename
    assert "from-host.txt" in names
    assert stack.sql(f"select status from node where id = '{doomed_id}'") == "missing"
    status, got, _ = raw(carol, "GET", f"/api/v1/nodes/{file_id}/content")
    assert status == 200 and got == b"outside change"
    status, out = js(carol, "GET", f"/api/v1/nodes/{doomed_id}/content")
    assert status == 409 and out["detail"]["code"] == "CONTENT_MISSING"
    assert (
        stack.sql(
            f"select actor_kind || '/' || coalesce(actor_user_id::text, '-') from file_event "
            f"where node_id = '{file_id}' and action = 'external_moved'"
        )
        == "external_filesystem/-"
    )
    assert (
        stack.sql(
            "select count(*) from scan_run where outcome in ('ok','partial') and trigger = 'manual'"
        )
        != "0"
    )
    # a second rescan inside a minute is refused
    assert js(carol, "POST", f"/api/v1/nodes/{docs_id}/rescan")[0] == 429
