"""M22: the Docker Swarm stack variant, deployed with `docker stack deploy` on a real (single-node)
swarm and checked from inside the overlay network. Skipped unless FILECANOPY_TEST_SWARM=1, because
it turns the Docker engine into a swarm manager (CI runners are disposable; your own machine is
not). CI sets it. The images are the locally built ones tagged as a release would be, so the stack
file is exercised unchanged and no registry is involved.

Random credentials and generated bytes only.
"""

import json
import os
import secrets
import subprocess
import time
from collections.abc import Iterator
from pathlib import Path

import pytest
from test_stack import REPO

pytestmark = [
    pytest.mark.compose,
    pytest.mark.skipif(
        os.environ.get("FILECANOPY_TEST_SWARM") != "1",
        reason="set FILECANOPY_TEST_SWARM=1 to run (it initialises a Docker swarm)",
    ),
]

STACK_FILE = REPO / "deploy" / "contrib" / "swarm" / "docker-stack.yml"
PREFIX = "filecanopy-m22test"
VERSION = "citest"
IMAGES = {
    "filecanopy-postgres:dev": f"{PREFIX}-postgres:{VERSION}",
    "filecanopy-api:dev": f"{PREFIX}-api:{VERSION}",
    "filecanopy-web:dev": f"{PREFIX}-web:{VERSION}",
}


def docker(
    *args: str, check: bool = True, stdin: str | None = None
) -> subprocess.CompletedProcess[str]:
    r = subprocess.run(  # noqa: S603
        ["docker", *args],  # noqa: S607
        capture_output=True,
        text=True,
        input=stdin,
        timeout=600,
        check=False,
    )
    if check and r.returncode != 0:
        raise AssertionError(f"docker {' '.join(args)} failed:\n{r.stdout}\n{r.stderr}")
    return r


class Swarm:
    def __init__(self, tmp: Path) -> None:
        self.name = f"fcstack{secrets.token_hex(3)}"
        self.library = tmp / "library"
        self.app_data = tmp / "app-data"
        self.library.mkdir()
        self.app_data.mkdir()
        self.secret = f"{self.name}_pg"
        # Characters that break a naive database URL: the stack must quote the secret.
        self.password = secrets.token_urlsafe(16) + "@:/?#%x"
        uid = str(os.getuid()) if hasattr(os, "getuid") else "10001"
        gid = str(os.getgid()) if hasattr(os, "getgid") else "10001"
        self.env = {
            **os.environ,
            "FILECANOPY_IMAGE_PREFIX": PREFIX,
            "FILECANOPY_VERSION": VERSION,
            "FILECANOPY_LIBRARY_PATH": str(self.library),
            "FILECANOPY_APP_DATA_PATH": str(self.app_data),
            "FILECANOPY_PG_SECRET": self.secret,
            "FILECANOPY_UID": uid,
            "FILECANOPY_GID": gid,
        }

    def stack_cmd(self, *args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
        r = subprocess.run(  # noqa: S603
            ["docker", "stack", *args],  # noqa: S607
            env=self.env,
            capture_output=True,
            text=True,
            timeout=600,
            check=False,
        )
        if check and r.returncode != 0:
            raise AssertionError(f"stack {' '.join(args)} failed:\n{r.stdout}\n{r.stderr}")
        return r

    def running_replicas(self) -> dict[str, str]:
        out = docker(
            "service", "ls", "--filter", f"label=com.docker.stack.namespace={self.name}",
            "--format", "{{.Name}} {{.Replicas}}",
        ).stdout  # fmt: skip
        return dict(line.split() for line in out.splitlines())

    def wait_converged(self, timeout: float = 240) -> None:
        deadline = time.time() + timeout
        last: dict[str, str] = {}
        while time.time() < deadline:
            last = self.running_replicas()
            if len(last) == 3 and all(v.startswith("1/1") for v in last.values()):
                # "running" is not "healthy": wait until the API answers on the overlay too.
                if self.probe("http://web:8080/api/v1/health")[0] == 200:
                    return
            time.sleep(3)
        logs = {s: docker("service", "logs", "--tail", "30", f"{self.name}_{s}", check=False).stdout
                for s in ("postgres", "api", "web")}  # fmt: skip
        raise AssertionError(f"stack never converged: {last}\n{logs}")

    def probe(self, url: str) -> tuple[int, str]:
        """GET a URL from a throwaway container on the stack's edge network."""
        code = (
            "import sys,urllib.request,urllib.error\n"
            "try:\n r=urllib.request.urlopen(sys.argv[1],timeout=5)\n"
            " print(r.status); print(r.read().decode())\n"
            "except urllib.error.HTTPError as e: print(e.code); print(e.read().decode())\n"
            "except Exception as e: print(0); print(e)\n"
        )  # fmt: skip
        r = docker(
            "run", "--rm", "--network", f"{self.name}_edge", "--entrypoint", "python",
            f"{PREFIX}-api:{VERSION}", "-c", code, url,
            check=False,
        )  # fmt: skip
        lines = r.stdout.split("\n", 1)
        try:
            return int(lines[0]), lines[1] if len(lines) > 1 else ""
        except ValueError:
            return 0, r.stdout + r.stderr


def instance_id(swarm: Swarm) -> str:
    task = docker(
        "ps", "-q", "--filter", f"label=com.docker.swarm.service.name={swarm.name}_postgres"
    ).stdout.strip()
    query = "select value #>> '{}' from app_setting where key='instance_id'"
    cmd = ["exec", task, "psql", "-U", "filecanopy", "-d", "filecanopy", "-tAc", query]
    return docker(*cmd).stdout.strip()


@pytest.fixture(scope="module")
def swarm(tmp_path_factory: pytest.TempPathFactory) -> Iterator[Swarm]:
    if any(docker("image", "inspect", local, check=False).returncode != 0 for local in IMAGES):
        subprocess.run(  # noqa: S603
            [  # noqa: S607
                "docker",
                "compose",
                "-f",
                str(REPO / "deploy" / "compose.yaml"),
                "-f",
                str(REPO / "deploy" / "contrib" / "build.yaml"),
                "build",
            ],  # fmt: skip
            env={
                **os.environ,
                "FILECANOPY_IMAGE_PREFIX": "filecanopy",
                "FILECANOPY_VERSION": "dev",
            },
            check=True,
            capture_output=True,
            timeout=1800,
        )
    for local, release in IMAGES.items():
        docker("tag", local, release)
    state = docker("info", "--format", "{{.Swarm.LocalNodeState}}").stdout.strip()
    joined_here = state != "active"
    if joined_here:
        if docker("swarm", "init", check=False).returncode != 0:
            docker("swarm", "init", "--advertise-addr", "127.0.0.1")
    s = Swarm(tmp_path_factory.mktemp("stack"))
    node = docker("node", "ls", "--filter", "role=manager", "-q").stdout.split()[0]
    docker("node", "update", "--label-add", "filecanopy.data=true", node)
    docker("secret", "create", s.secret, "-", stdin=s.password)
    try:
        yield s
    finally:
        s.stack_cmd("rm", s.name, check=False)
        time.sleep(8)
        docker("secret", "rm", s.secret, check=False)
        docker("node", "update", "--label-rm", "filecanopy.data", node, check=False)
        docker(
            "volume",
            "prune",
            "-f",
            "--filter",
            f"label=com.docker.stack.namespace={s.name}",
            check=False,
        )
        if joined_here:
            docker("swarm", "leave", "--force", check=False)


def test_stack_file_is_valid_and_publishes_nothing(swarm: Swarm) -> None:
    out = swarm.stack_cmd("config", "-c", str(STACK_FILE)).stdout
    assert "build:" not in out
    assert "published:" not in out and "ports:" not in out, "the stack must not open host ports"
    assert f"{PREFIX}-api:{VERSION}" in out
    r = subprocess.run(  # noqa: S603
        ["docker", "stack", "config", "-c", str(STACK_FILE)],  # noqa: S607
        env={k: v for k, v in swarm.env.items() if k != "FILECANOPY_VERSION"},
        capture_output=True,
        text=True,
        check=False,
    )
    assert r.returncode != 0 and "FILECANOPY_VERSION" in r.stderr


def test_stack_deploys_converges_and_serves(swarm: Swarm) -> None:
    swarm.stack_cmd(
        "deploy", "--resolve-image", "never", "--detach=true", "-c", str(STACK_FILE), swarm.name
    )
    swarm.wait_converged()
    status, body = swarm.probe("http://web:8080/api/v1/health")
    assert status == 200 and json.loads(body)["status"] == "ok"
    status, body = swarm.probe("http://web:8080/")
    assert status == 200 and "FileCanopy" in body
    # Migrations ran from the API's own start-up, and the password is not in the service spec.
    spec = docker("service", "inspect", f"{swarm.name}_api").stdout
    assert swarm.password not in spec
    assert docker("service", "inspect", f"{swarm.name}_postgres").stdout.count(swarm.password) == 0
    assert "pg_password" in spec


def test_stack_runs_as_the_configured_user_with_a_sealed_filesystem(swarm: Swarm) -> None:
    spec = json.loads(docker("service", "inspect", f"{swarm.name}_api").stdout)[0]["Spec"][
        "TaskTemplate"
    ]
    container = spec["ContainerSpec"]
    assert container["User"] == f"{swarm.env['FILECANOPY_UID']}:{swarm.env['FILECANOPY_GID']}"
    assert container["ReadOnly"] is True
    assert container["CapabilityDrop"] == ["ALL"]
    web = json.loads(docker("service", "inspect", f"{swarm.name}_web").stdout)[0]
    web_container = web["Spec"]["TaskTemplate"]["ContainerSpec"]
    assert web_container["ReadOnly"] is True and web_container["CapabilityDrop"] == ["ALL"]
    assert (
        "Ports" not in web["Spec"].get("EndpointSpec", {})
        or not web["Spec"]["EndpointSpec"]["Ports"]
    )


def test_data_survives_a_service_restart_and_a_stack_redeploy(swarm: Swarm) -> None:
    (swarm.library / "keep.txt").write_text("still here\n")
    instance = instance_id(swarm)
    assert len(instance) == 36
    docker("service", "update", "--force", "--detach=true", f"{swarm.name}_api")
    swarm.stack_cmd("rm", swarm.name)
    time.sleep(10)
    swarm.stack_cmd(
        "deploy", "--resolve-image", "never", "--detach=true", "-c", str(STACK_FILE), swarm.name
    )
    swarm.wait_converged()
    again = instance_id(swarm)
    assert again == instance, "the database volume must outlive the stack"
    assert (swarm.library / "keep.txt").read_text() == "still here\n"
