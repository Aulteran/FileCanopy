"""M07 against the real stack: migration 0009, delete to the hidden library trash on PostgreSQL
behind nginx, restore, the confirmation for delete-forever, the "check and release" action for an
item flagged `reconcile_needed`, and an API killed in the middle of a burst of deletes: afterwards
every file is either where it was or in the trash, nothing is stuck busy, nothing is lost.

Run after the auth and storage suites (they perform the first-run setup this one reuses). Random
credentials and generated bytes only."""

import json
import os
import threading
import uuid
from pathlib import Path
from typing import Any

import pytest
from test_files_stack import js, raw
from test_stack import Stack
from test_storage_stack import invite_and_login, root_node, setup_admin, user_id

pytestmark = pytest.mark.compose

TRASH = ".filecanopy-trash"


@pytest.fixture
def stack(app_stack: Stack) -> Stack:
    return app_stack


class Member:
    def __init__(self, stack: Stack, name: str) -> None:
        admin = setup_admin(stack)
        tag = uuid.uuid4().hex[:6]
        self.stack = stack
        self.email = f"{name}{tag}@example.com"
        self.client = invite_and_login(stack, admin, self.email)
        self.uid = user_id(stack, self.email)
        self.root = root_node(stack, f"personal/{self.uid}")
        self.disk = stack.library / "personal" / self.uid
        self.root_id = stack.sql(f"select root_id from node where id = '{self.root}'")

    def folder(self, name: str) -> str:
        status, out = js(self.client, "POST", f"/api/v1/nodes/{self.root}/folders", {"name": name})
        assert status == 201, out
        return str(out["node"]["id"])

    def upload(self, parent: str, name: str, data: bytes) -> dict[str, Any]:
        status, body, _ = raw(
            self.client,
            "POST",
            f"/api/v1/nodes/{parent}/files?name={name}",
            data,
            **{"Content-Type": "application/octet-stream"},
        )
        assert status == 201, body
        return dict(json.loads(body)["node"])

    def delete(self, node: dict[str, Any]) -> tuple[int, Any]:
        return js(
            self.client,
            "DELETE",
            f"/api/v1/nodes/{node['id']}?expected_revision={node['revision']}",
            **{"Idempotency-Key": uuid.uuid4().hex},
        )

    def trash_dir(self, item: str) -> Path:
        return self.stack.library / TRASH / self.root_id / item


def test_trash_restore_and_delete_forever_on_postgres(stack: Stack) -> None:
    assert stack.sql("select version_num from alembic_version") == "0020"
    m = Member(stack, "tina")
    docs = m.folder("Docs")
    data = os.urandom(300_000)
    file = m.upload(docs, "keep.bin", data)
    status, out = m.delete(file)
    assert status == 200, out
    item = out["item"]["id"]
    assert not (m.disk / "Docs" / "keep.bin").exists()
    assert (m.trash_dir(item) / "keep.bin").read_bytes() == data  # an ordinary file, same device
    assert oct((stack.library / TRASH).stat().st_mode & 0o777) == "0o700"
    assert stack.sql(f"select status from node where id = '{file['id']}'") == "trashed"

    status, listing = js(m.client, "GET", "/api/v1/trash")
    assert status == 200 and [i["id"] for i in listing["items"]] == [item]

    # the hidden trash is invisible to the browse API
    status, kids = js(m.client, "GET", f"/api/v1/nodes/{docs}/children")
    assert kids["items"] == []

    status, back = js(m.client, "POST", f"/api/v1/trash/{item}/restore", {})
    assert status == 200, back
    assert (m.disk / "Docs" / "keep.bin").read_bytes() == data
    assert not m.trash_dir(item).exists() or not any(m.trash_dir(item).iterdir())

    # delete forever needs the item's confirmation token
    file = js(m.client, "GET", f"/api/v1/nodes/{docs}/children")[1]["items"][0]
    status, out = m.delete(file)
    item = out["item"]["id"]
    assert js(m.client, "DELETE", f"/api/v1/trash/{item}?confirm=wrong")[0] == 409
    assert (m.trash_dir(item) / "keep.bin").exists()
    token = out["item"]["confirm_token"]
    assert js(m.client, "DELETE", f"/api/v1/trash/{item}?confirm={token}")[0] == 200
    assert not m.trash_dir(item).exists()
    assert stack.sql(f"select status from trash_item where id = '{item}'") == "purged"


def test_check_and_release_for_a_flagged_item(stack: Stack) -> None:
    m = Member(stack, "carl")
    docs = m.folder("Docs")
    file = m.upload(docs, "flagged.bin", b"payload")
    item = m.delete(file)[1]["item"]["id"]

    assert js(m.client, "POST", f"/api/v1/trash/{item}/check")[0] == 409  # not flagged

    stack.sql(f"update trash_item set status = 'reconcile_needed' where id = '{item}'")
    assert js(m.client, "POST", f"/api/v1/trash/{item}/restore", {})[0] == 409
    status, out = js(m.client, "POST", f"/api/v1/trash/{item}/check")
    assert status == 200 and out["released"] is True and out["item"]["status"] == "in_trash"
    assert (
        stack.sql(
            f"select count(*) from file_event where node_id = '{file['id']}' and action = 'checked'"
        )
        == "1"
    )

    # the bytes vanish: the check says so, changes nothing, and a person can still delete it
    stack.sql(f"update trash_item set status = 'reconcile_needed' where id = '{item}'")
    (m.trash_dir(item) / "flagged.bin").unlink()
    status, out = js(m.client, "POST", f"/api/v1/trash/{item}/check")
    assert status == 200 and out["released"] is False and out["reason"] == "entry_missing"
    assert out["item"]["status"] == "reconcile_needed"
    token = out["item"]["confirm_token"]
    assert js(m.client, "DELETE", f"/api/v1/trash/{item}?confirm={token}")[0] == 200


def test_check_and_release_for_the_whole_root(stack: Stack) -> None:
    m = Member(stack, "rhea")
    docs = m.folder("Docs")
    items = [
        m.delete(m.upload(docs, f"w{i}.bin", b"x" * (i + 1)))[1]["item"]["id"] for i in range(2)
    ]
    for item in items:
        stack.sql(f"update trash_item set status = 'reconcile_needed' where id = '{item}'")
    listed = js(m.client, "GET", "/api/v1/trash")[1]
    assert [r["flagged_count"] for r in listed["roots"]] == [2]
    status, out = js(m.client, "POST", f"/api/v1/roots/{m.root}/trash/check")
    assert status == 200 and out == {"checked": 2, "released": 2, "still_flagged": 0}
    assert (
        stack.sql(
            "select count(*) from trash_item "
            f"where id in ('{items[0]}','{items[1]}') and status = 'in_trash'"
        )
        == "2"
    )


def test_killing_the_api_during_deletes_loses_nothing(stack: Stack) -> None:
    m = Member(stack, "kira")
    box = m.folder("Burst")
    nodes = [m.upload(box, f"f{i:03d}.bin", os.urandom(2000 + i)) for i in range(60)]
    expected = {n["name"]: (m.disk / "Burst" / n["name"]).read_bytes() for n in nodes}

    done = 0
    lock = threading.Lock()
    enough = threading.Event()

    def worker(batch: list[dict[str, Any]]) -> None:
        nonlocal done
        for node in batch:
            try:
                status, _ = m.delete(node)
            except (OSError, ValueError):  # the API was killed under us
                return
            if status == 200:
                with lock:
                    done += 1
                    if done >= 8:
                        enough.set()

    threads = [threading.Thread(target=worker, args=(nodes[i::6],)) for i in range(6)]
    for t in threads:
        t.start()
    # kill once some deletes have finished, while the others are still running
    assert enough.wait(timeout=60)
    stack.compose("kill", "api")
    for t in threads:
        t.join(timeout=60)
    assert 8 <= done < 60, f"{done} of 60 deletes finished: the kill interrupted nothing"
    stack.compose("up", "-d", "--wait", "--wait-timeout", "180", "api")
    stack.wait_health("ok", timeout=120)

    # every file is in exactly one place: its folder or an item in the trash
    trashed = {
        p.name: p.read_bytes()
        for p in (stack.library / TRASH / m.root_id).rglob("*")
        if p.is_file()
    }
    kept = {p.name: p.read_bytes() for p in (m.disk / "Burst").iterdir()}
    assert set(trashed).isdisjoint(kept)
    assert {**trashed, **kept} == expected
    # the database agrees: nothing stuck busy, no unfinished operation, every item has its bytes
    assert (
        stack.sql(f"select count(*) from node where parent_id = '{box}' and status = 'busy'") == "0"
    )
    assert (
        stack.sql(
            f"select count(*) from file_operation "
            f"where actor_user_id = '{m.uid}' and status = 'planned'"
        )
        == "0"
    )
    # per file: still in the folder means an active node; in the trash means trashed (or flagged)
    states = dict(
        row.split(":")
        for row in stack.sql(
            f"select name || ':' || status from node where parent_id = '{box}'"
        ).splitlines()
    )
    assert set(states) == set(expected)
    for name in kept:
        assert states[name] == "active", (name, states[name])
    for name in trashed:
        assert states[name] in ("trashed", "reconcile_needed"), (name, states[name])
    listing = js(m.client, "GET", "/api/v1/trash?limit=200")[1]
    names = {i["name"] for i in listing["items"] if i["status"] == "in_trash"}
    assert names >= set(trashed) - {
        n
        for n in trashed
        if stack.sql(f"select status from node where name = '{n}'") == "reconcile_needed"
    }
    for item in listing["items"]:
        if item["status"] == "reconcile_needed":
            out = js(m.client, "POST", f"/api/v1/trash/{item['id']}/check")[1]
            assert "released" in out
