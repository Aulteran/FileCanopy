"""M23 against the real stack: many people working in one shared folder at once on PostgreSQL, and
the container logs after requests that carried secrets in their address.

Run with the other `app` suite files (it reuses their first-run setup). Random credentials and
generated bytes only.
"""

import threading
import uuid
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor

import pytest
from test_auth_stack import Client
from test_files_stack import raw
from test_stack import Stack
from test_storage_stack import invite_and_login, setup_admin

pytestmark = pytest.mark.compose

PEOPLE = 6
FILES_EACH = 15


@pytest.fixture
def stack(app_stack: Stack) -> Stack:
    return app_stack


def shared_root(stack: Stack) -> str:
    return stack.sql(
        "select n.id from node n join storage_root r on r.id = n.root_id "
        "where n.parent_id is null and r.kind = 'shared'"
    )


def upload(c: Client, folder: str, name: str, data: bytes) -> int:
    status, _, _ = raw(
        c,
        "POST",
        f"/api/v1/nodes/{folder}/files?name={name}&on_conflict=reject",
        data,
        **{
            "Content-Type": "application/octet-stream",
            "Idempotency-Key": uuid.uuid4().hex,
        },
    )
    return status


def run_all(jobs: list[Callable[[], None]]) -> None:
    with ThreadPoolExecutor(max_workers=len(jobs)) as pool:
        futures = [pool.submit(job) for job in jobs]
        for future in futures:
            future.result()  # a request failure must fail the test, not just its thread


def test_many_people_working_in_one_folder_at_once(stack: Stack) -> None:
    admin = setup_admin(stack)
    tag = uuid.uuid4().hex[:6]
    people = [invite_and_login(stack, admin, f"p{i}{tag}@example.com") for i in range(PEOPLE)]
    status, made, _ = admin.call(
        "POST", f"/api/v1/nodes/{shared_root(stack)}/folders", {"name": f"Crowd-{tag}"}
    )
    assert status == 201, made
    folder = made["node"]["id"]
    lock = threading.Lock()

    # 1. everyone uploads their own files at the same time
    codes: list[int] = []

    def uploads(i: int) -> Callable[[], None]:
        def go() -> None:
            for n in range(FILES_EACH):
                code = upload(people[i], folder, f"p{i}-f{n:02}.bin", bytes([i, n]) * 500)
                with lock:
                    codes.append(code)

        return go

    run_all([uploads(i) for i in range(PEOPLE)])
    assert codes.count(201) == PEOPLE * FILES_EACH, sorted(set(codes))
    assert stack.sql(f"select count(*) from node where parent_id = '{folder}'") == str(
        PEOPLE * FILES_EACH
    )

    # 2. everyone races to create the same name: one wins, the rest get a clean conflict
    results: list[int] = []

    def contest(i: int) -> Callable[[], None]:
        def go() -> None:
            code = upload(people[i], folder, "contested.bin", b"x" * 100)
            with lock:
                results.append(code)

        return go

    run_all([contest(i) for i in range(PEOPLE)])
    assert sorted(results) == [201] + [409] * (PEOPLE - 1), results
    assert (
        stack.sql(
            f"select count(*) from node where parent_id = '{folder}' and name = 'contested.bin'"
        )
        == "1"
    )

    # 3. renames and listings at the same time: conflicts are clean, never a server error
    status, listing, _ = admin.call("GET", f"/api/v1/nodes/{folder}/children")
    assert status == 200, listing
    nodes = [n for n in listing["items"] if n["name"].startswith("p0-")][:8]
    assert len(nodes) == 8
    renames: list[tuple[str, int]] = []
    listings: list[int] = []

    def churn(i: int) -> Callable[[], None]:
        def go() -> None:
            for n, node in enumerate(nodes):
                node_id = node["id"]
                s1, _, _ = people[i].call(
                    "POST",
                    f"/api/v1/nodes/{node_id}/rename",
                    {"name": f"r{i}-{n}.bin", "expected_revision": node["revision"]},
                )
                s2, _, _ = people[i].call("GET", f"/api/v1/nodes/{folder}/children")
                with lock:
                    renames.append((node_id, s1))
                    listings.append(s2)

        return go

    run_all([churn(i) for i in range(PEOPLE)])
    for node in nodes:
        statuses = [status for node_id, status in renames if node_id == node["id"]]
        assert sorted(statuses) == [200] + [409] * (PEOPLE - 1), statuses
    assert listings == [200] * (PEOPLE * len(nodes)), listings

    # nothing half-done, no case-insensitive duplicates, no staging leftovers
    assert stack.sql("select count(*) from file_operation where status = 'planned'") == "0"
    assert (
        stack.sql(
            "select count(*) from (select lower(name) from node "
            f"where parent_id = '{folder}' and status = 'active' "
            "group by lower(name) having count(*) > 1) d"
        )
        == "0"
    )
    assert list(stack.library.rglob(".filecanopy-tmp-*")) == []
    in_db = set(
        stack.sql(
            f"select string_agg(name, ',') from node where parent_id = '{folder}' "
            "and status = 'active'"
        ).split(",")
    )
    on_disk = {p.name for p in stack.library.rglob(f"Crowd-{tag}/*")}
    assert on_disk == in_db


def test_container_logs_hold_no_query_string_or_secret(stack: Stack) -> None:
    admin = setup_admin(stack)
    canary = "CANARY" + uuid.uuid4().hex
    assert admin.call("GET", f"/api/v1/search?q={canary}")[0] == 200
    # The callback redirects to the SPA. raw follows it without trying to parse HTML as JSON.
    status, body, headers = raw(
        admin, "GET", f"/api/v1/auth/oidc/callback?code={canary}code&state={canary}state"
    )
    assert status == 200 and headers["Content-Type"].startswith("text/html"), body
    assert b"FileCanopy" in body
    assert (
        Client(stack).call(
            "POST",
            "/api/v1/auth/login",
            {"email": "x@example.com", "password": canary + "pw"},
        )[0]
        == 401
    )
    result = stack.compose("logs", "--no-color", "web", "api")
    logs = result.stdout + result.stderr
    assert canary not in logs
    assert "/api/v1/search" in logs  # the access lines exist, without the address' query
    assert "/api/v1/auth/oidc/callback" in logs
