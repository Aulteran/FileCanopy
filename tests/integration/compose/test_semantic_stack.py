"""M19 against the real stack: the pgvector image, migration 0022 and the semantic code path on
PostgreSQL (vector column, bound vector literals, the `<=>` operator, the dimension-checked scan).

The embedding endpoint is a mock at the HTTP transport inside a script that runs in the API
container, so no model is needed. The script forces the module's `is_active` switch on for itself
only: the configuration stored in the database stays "off", so the running server never touches
the data. Random credentials and generated bytes only."""

import json
