import uuid
from urllib.parse import quote

import pytest
from test_files_stack import js
from test_stack import Stack
from test_trash_stack import Member

pytestmark = pytest.mark.compose

SCRIPT = """
import json, sys
import httpx
from sqlalchemy import select, text
from sqlalchemy.orm import sessionmaker
from app.config import load_settings
from app.db.engine import make_engine
from app.db.models import SearchChunk
from app.policy.model import Actor
from app.search import semantic

owner, other = sys.argv[1], sys.argv[2]
settings = load_settings()
sessions = sessionmaker(make_engine(settings), expire_on_commit=False)
semantic.is_active = lambda db, s: True  # this process only; the stored config says "off"

def vec(t):
    t = t.lower()
    v = [0.0] * 8
    v[7] = 0.1
    for i, words in enumerate((("holiday", "vacation"), ("invoice", "bill"))):
        if any(w in t for w in words):
            v[i] += 3.0
    return v

def handler(request):
    body = json.loads(request.content)
    return httpx.Response(200, json={"embeddings": [vec(x) for x in body["input"]]})

sem = semantic.Semantic(settings, sessions, transport=httpx.MockTransport(handler))
with sessions() as db:
    cfg = semantic.SemanticConfig(
        enabled=False, kind="ollama", endpoint="http://127.0.0.1:8081", model="m",
        dim=8, generation=1, healthy=True, verified="ollama|http://127.0.0.1:8081|m",
    )
    semantic.save_config(db, cfg)
    db.commit()
idx = semantic.SemanticIndexer(sem)
ran = idx.tick()
out = {"ran": ran, "ready": None}
with sessions() as db:
    out["ready"] = semantic.pgvector_ready(db)
    out["chunks"] = len(list(db.scalars(select(SearchChunk.id))))
    out["dims"] = db.scalar(text("select max(vector_dims(embedding)) from search_chunk"))
    mine = semantic.semantic_hits(db, Actor(__import__("uuid").UUID(owner)), sem, "vacation trip")
    theirs = semantic.semantic_hits(db, Actor(__import__("uuid").UUID(other)), sem, "vacation trip")
    unrelated = semantic.semantic_hits(db, Actor(__import__("uuid").UUID(owner)), sem, "zzz qqq")
    out["mine"] = [h.name for h in mine or []]
    out["theirs"] = [h.name for h in theirs or []]
    out["unrelated"] = [h.name for h in unrelated or []]
print(json.dumps(out))
"""


@pytest.fixture
def stack(app_stack: Stack) -> Stack:
    return app_stack


def test_the_image_has_pgvector_and_the_column_is_a_vector(stack: Stack) -> None:
    assert stack.sql("select version_num from alembic_version") == "0027"
    assert stack.sql("select count(*) from pg_available_extensions where name = 'vector'") == "1"
    assert stack.sql("select extname from pg_extension where extname = 'vector'") == "vector"
    assert stack.sql(
        "select udt_name from information_schema.columns "
        "where table_name = 'search_chunk' and column_name = 'embedding'"
    ) == ("vector")
    # the extension works for ordinary SQL too
    assert stack.sql("select round(('[1,0]'::vector <=> '[0,1]'::vector)::numeric, 1)") == "1.0"


def test_embedding_search_runs_on_pgvector_and_respects_ownership(stack: Stack) -> None:
    alice, bob = Member(stack, "alice"), Member(stack, "bob")
    word = "zyx" + uuid.uuid4().hex[:8]
    alice.upload(alice.root, "trip.txt", f"{word} our holiday by the sea".encode())
    deadline = time.monotonic() + 90
    while time.monotonic() < deadline:  # the text indexer (M11) must have read it first
        status, out = js(alice.client, "GET", f"/api/v1/search?q={quote(word)}")
        assert status == 200, out
        if out["hits"]:
            break
        time.sleep(2)
    else:
        raise AssertionError("the text indexer never picked up the file")
    r = stack.compose("exec", "-T", "api", "python", "-c", SCRIPT, alice.uid, bob.uid)
    out = json.loads(r.stdout.strip().splitlines()[-1])
    assert out["ready"] is True and out["ran"] >= 1
    assert out["chunks"] >= 1 and out["dims"] == 8
    assert "trip.txt" in out["mine"]  # nearest neighbour through the real `<=>` operator
    assert out["theirs"] == []  # another member's query never sees it
    assert out["unrelated"] == []  # below the similarity floor
    # clean up so the shared stack is as it was (and the stored config never enabled anything)
    stack.sql("delete from search_chunk")
    stack.sql("delete from search_embed")
    stack.sql("delete from app_setting where key = 'semantic.config'")
