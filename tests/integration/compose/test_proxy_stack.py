"""M07c (ADR-018) against the real stack: FileCanopy behind real outer TLS reverse proxies.

Three outer proxies run as containers next to the stack: nginx (configured like Nginx Proxy
Manager, using deploy/proxy/npm-advanced.conf), Caddy and Traefik. A fourth nginx server shows
what happens with an out-of-the-box nginx (1 MB body limit) and a fifth does not forward `Host`.
The tests follow the order of the file: they walk one stack through the trusted-proxy settings.

Needs Docker and pulls caddy and traefik images (override with FILECANOPY_TEST_CADDY_IMAGE and
FILECANOPY_TEST_TRAEFIK_IMAGE). Random credentials, a throwaway self-signed certificate and
generated bytes only.
"""

import hashlib
import json
import os
import random
import re
import secrets
import ssl
import subprocess
import urllib.error
import urllib.request
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest
from test_stack import REPO, Stack, free_port

pytestmark = pytest.mark.compose

PASSWORD = "correct horse battery staple"
SPOOF = "203.0.113.7"  # TEST-NET-3: never a real client
NPM_ADVANCED = REPO / "deploy" / "proxy" / "npm-advanced.conf"
NGINX_IMAGE = os.environ.get(
    "FILECANOPY_TEST_NGINX_IMAGE", "nginxinc/nginx-unprivileged:1.28-alpine"
)
CADDY_IMAGE = os.environ.get("FILECANOPY_TEST_CADDY_IMAGE", "caddy:2-alpine")
TRAEFIK_IMAGE = os.environ.get("FILECANOPY_TEST_TRAEFIK_IMAGE", "traefik:v3.1")

# name -> (last octet of the static address, container port)
PROXIES = {"nginx": 10, "caddy": 11, "traefik": 12}
# What a stock install of nginx does: a 1 MB body limit. Another server block, same container.
STOCK = "nginx-stock"
NOHOST = "nginx-nohost"


class ProxyStack(Stack):
    """The core stack plus outer proxies on a network with fixed addresses."""

    def __init__(self, tmp: Path, name: str) -> None:
        super().__init__(tmp, name)
        rnd = random.Random(secrets.token_bytes(8))  # noqa: S311
        self.subnet = f"10.{rnd.randint(150, 250)}.{rnd.randint(0, 255)}"
        self.setup_token = secrets.token_urlsafe(32)
        self.env["FILECANOPY_SETUP_TOKEN"] = self.setup_token
        self.ports = {n: free_port() for n in (*PROXIES, STOCK, NOHOST)}
        self.dir = tmp / "proxy"
        self.dir.mkdir()
        self.files.append(self._write_override(tmp))
        self.cert = self.dir / "cert.pem"
        self.ssl = ssl.create_default_context(cafile=str(self.cert))

    def ip(self, proxy: str) -> str:
        return f"{self.subnet}.{PROXIES.get(proxy, 10)}"

    def _write_override(self, tmp: Path) -> Path:
        d = self.dir
        key = d / "key.pem"
        cert = d / "cert.pem"
        subprocess.run(  # noqa: S603
            [
                "openssl",
                "req",
                "-x509",
                "-newkey",
                "rsa:2048",
                "-nodes",
                "-days",
                "2",
                "-keyout",
                str(key),
                "-out",
                str(cert),
                "-subj",
                "/CN=localhost",
                "-addext",
                "subjectAltName=DNS:localhost,IP:127.0.0.1",
            ],  # fmt: skip
            check=True,
            capture_output=True,
        )
        for f in (key, cert):
            f.chmod(0o644)
        d.chmod(0o755)

        # One nginx container, four server blocks (all upstream lookups are repeated, like
        # deploy/proxy/nginx.conf, because the web container is recreated between phases).
        def server(port: int, extra: str, host: str) -> str:
            return f"""
server {{
    listen {port} ssl;
    ssl_certificate /certs/cert.pem;
    ssl_certificate_key /certs/key.pem;
    {extra}
    location / {{
        resolver 127.0.0.11 valid=2s;
        set $up http://web:8080;
        proxy_pass $up;
        proxy_http_version 1.1;
        {host}
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
    }}
}}"""

        (d / "nginx.conf").write_text(
            server(8443, "include /npm-advanced.conf;", "proxy_set_header Host $http_host;")
            + server(8444, "include /npm-advanced.conf;", "")  # Host becomes web:8080
            + server(8445, "", "proxy_set_header Host $http_host;")  # stock: 1 MB body limit
        )
        (d / "Caddyfile").write_text(
            "{\n auto_https off\n admin off\n}\n"
            ":8443 {\n tls /certs/cert.pem /certs/key.pem\n"
            " reverse_proxy web:8080 {\n  flush_interval -1\n }\n}\n"
        )
        (d / "traefik.yml").write_text(
            "http:\n  routers:\n    fc:\n      rule: PathPrefix(`/`)\n"
            "      entryPoints: [websecure]\n      service: fc\n      tls: {}\n"
            "  services:\n    fc:\n      loadBalancer:\n        servers:\n"
            "          - url: http://web:8080\n"
            "tls:\n  certificates:\n    - certFile: /certs/cert.pem\n"
            "      keyFile: /certs/key.pem\n"
        )
        user = f'user: "{os.getuid()}:{os.getgid()}"' if hasattr(os, "getuid") else ""

        nginx_ports = (
            f'    ports: ["127.0.0.1:{self.ports["nginx"]}:8443", '
            f'"127.0.0.1:{self.ports[NOHOST]}:8444", "127.0.0.1:{self.ports[STOCK]}:8445"]\n'
        )
        override = f"""
services:
  outer-nginx:
    image: {NGINX_IMAGE}
    {user}
    depends_on: [web]
    networks:
      default:
        ipv4_address: {self.subnet}.10
{nginx_ports}    volumes:
      - {d}/cert.pem:/certs/cert.pem:ro
      - {d}/key.pem:/certs/key.pem:ro
      - {d}/nginx.conf:/etc/nginx/conf.d/default.conf:ro
      - {NPM_ADVANCED}:/npm-advanced.conf:ro
  outer-caddy:
    image: {CADDY_IMAGE}
    {user}
    depends_on: [web]
    environment: {{XDG_DATA_HOME: /tmp, XDG_CONFIG_HOME: /tmp}}
    command: ["caddy", "run", "--config", "/etc/caddy/Caddyfile", "--adapter", "caddyfile"]
    networks:
      default:
        ipv4_address: {self.subnet}.11
    ports: ["127.0.0.1:{self.ports["caddy"]}:8443"]
    volumes:
      - {d}/cert.pem:/certs/cert.pem:ro
      - {d}/key.pem:/certs/key.pem:ro
      - {d}/Caddyfile:/etc/caddy/Caddyfile:ro
  outer-traefik:
    image: {TRAEFIK_IMAGE}
    {user}
    depends_on: [web]
    command:
      - --entrypoints.websecure.address=:8443
      - --providers.file.filename=/etc/traefik/dynamic.yml
      - --log.level=ERROR
    networks:
      default:
        ipv4_address: {self.subnet}.12
    ports: ["127.0.0.1:{self.ports["traefik"]}:8443"]
    volumes:
      - {d}/cert.pem:/certs/cert.pem:ro
      - {d}/key.pem:/certs/key.pem:ro
      - {d}/traefik.yml:/etc/traefik/dynamic.yml:ro
networks:
  default:
    ipam:
      config:
        - subnet: {self.subnet}.0/24
"""
        path = tmp / "docker-compose.proxies.yml"
        path.write_text(override)
        return path

    # ---- requests through the outer proxies (TLS, verified against the throwaway certificate)

    def https(
        self,
        proxy: str,
        method: str,
        path: str,
        body: bytes | None = None,
        cookie: str | None = None,
        csrf: str | None = None,
        **headers: str,
    ) -> tuple[int, bytes, Any]:
        origin = f"https://localhost:{self.ports[proxy]}"
        hdrs = {"Origin": origin, **headers}
        if cookie:
            hdrs["Cookie"] = cookie
        if csrf and method != "GET":
            hdrs["X-CSRF-Token"] = csrf
        req = urllib.request.Request(  # noqa: S310
            origin + path, data=body, method=method, headers=hdrs
        )
        opener = urllib.request.build_opener(urllib.request.HTTPSHandler(context=self.ssl))
        try:
            with opener.open(req, timeout=180) as r:
                return r.status, r.read(), r.headers
        except urllib.error.HTTPError as e:
            return e.code, e.read(), e.headers

    def post_json(
        self, proxy: str, path: str, body: dict[str, Any], **headers: str
    ) -> tuple[int, dict[str, Any], Any]:
        status, raw, hdrs = self.https(
            proxy,
            "POST",
            path,
            json.dumps(body).encode(),
            **{"Content-Type": "application/json", **headers},
        )
        return status, json.loads(raw or b"{}"), hdrs

    def failed_login(self, proxy: str, **headers: str) -> int:
        email = f"nobody{secrets.token_hex(4)}@example.com"
        return self.post_json(
            proxy,
            "/api/v1/auth/login",
            {"email": email, "password": "wrong password"},
            **headers,
        )[0]

    def last_audit_ip(self, action: str = "login.failed") -> str:
        return self.sql(
            f"select ip from auth_audit where action='{action}' order by id desc limit 1"
        )

    def direct(self, path: str, **headers: str) -> tuple[int, Any]:
        req = urllib.request.Request(f"http://127.0.0.1:{self.port}{path}", headers=headers)  # noqa: S310
        with urllib.request.urlopen(req, timeout=10) as r:  # noqa: S310
            return r.status, r.headers

    def client_address_seen_by_proxy(self) -> str:
        """The address the outer nginx logged for the last request (the test's own address)."""
        logs = self.compose("logs", "--no-color", "outer-nginx").stdout
        lines = [ln for ln in logs.splitlines() if "/api/v1/auth/login" in ln]
        m = re.search(r"\|\s*(\d+\.\d+\.\d+\.\d+) - ", lines[-1])
        assert m, lines[-1:]
        return m.group(1)

    def reconfigure(self, **env: str) -> None:
        self.env.update(env)
        self.up()
        self.wait_proxies()

    def wait_proxies(self) -> None:
        import time

        deadline = time.time() + 90
        for proxy in PROXIES:
            while True:
                try:
                    if self.https(proxy, "GET", "/healthz")[0] == 200:
                        break
                except (OSError, urllib.error.URLError):
                    pass
                if time.time() > deadline:
                    raise AssertionError(f"{proxy} never became ready")
                time.sleep(1)


@pytest.fixture(scope="module")
def ps(tmp_path_factory: pytest.TempPathFactory) -> Iterator[ProxyStack]:
    s = ProxyStack(tmp_path_factory.mktemp("proxy"), f"fcproxy{secrets.token_hex(3)}")
    s.up()
    s.wait_proxies()
    yield s
    s.down(volumes=True)


def test_compose_passes_the_proxy_settings_through(ps: ProxyStack) -> None:
    cfg = json.loads(ps.compose("config", "--format", "json").stdout)["services"]
    assert "FILECANOPY_PUBLIC_URL" in cfg["api"]["environment"]
    assert "FILECANOPY_ALLOWED_ORIGINS" in cfg["api"]["environment"]
    assert cfg["web"]["environment"]["FILECANOPY_TRUSTED_PROXIES"] == ""
    assert cfg["web"]["environment"]["FILECANOPY_HSTS"] == "false"


def test_without_trusted_proxies_a_forwarded_header_is_never_believed(
    ps: ProxyStack,
) -> None:
    # The safe default: every visitor appears as the proxy, and a spoofed header changes nothing.
    for proxy in PROXIES:
        assert ps.failed_login(proxy, **{"X-Forwarded-For": SPOOF}) == 401
        assert ps.last_audit_ip() == ps.ip(proxy)


def test_trusted_proxy_gives_the_real_client_address(ps: ProxyStack) -> None:
    ps.reconfigure(FILECANOPY_TRUSTED_PROXIES=",".join(f"{ps.ip(p)}/32" for p in PROXIES))
    assert ps.failed_login("nginx") == 401
    client = ps.client_address_seen_by_proxy()
    assert client not in {ps.ip(p) for p in PROXIES}
    for proxy in PROXIES:
        # A spoofed X-Forwarded-For from the visitor is not believed; the proxy's peer is.
        assert ps.failed_login(proxy, **{"X-Forwarded-For": SPOOF}) == 401
        assert ps.last_audit_ip() == client, proxy
    # Straight to the bundled nginx (not a trusted proxy): the header is ignored as well.
    req = urllib.request.Request(  # noqa: S310
        f"http://127.0.0.1:{ps.port}/api/v1/auth/login",
        data=json.dumps({"email": "nobody@example.com", "password": "wrong password"}).encode(),
        headers={"Content-Type": "application/json", "X-Forwarded-For": SPOOF},
    )
    with pytest.raises(urllib.error.HTTPError) as err:
        urllib.request.urlopen(req, timeout=15)  # noqa: S310
    assert err.value.code == 401
    assert ps.last_audit_ip() not in {SPOOF, *(ps.ip(p) for p in PROXIES)}


def test_chain_of_proxies_and_throttle_isolation(ps: ProxyStack) -> None:
    # Two hops (like Cloudflare in front of a local proxy): the visitor's own address is the
    # rightmost one that is not a trusted proxy. Here the test's address stands in for hop one.
    client = ps.client_address_seen_by_proxy()
    trusted = [f"{ps.ip(p)}/32" for p in PROXIES] + [f"{client}/32"]
    ps.reconfigure(FILECANOPY_TRUSTED_PROXIES=",".join(trusted))
    assert ps.failed_login("nginx", **{"X-Forwarded-For": SPOOF}) == 401
    assert ps.last_audit_ip() == SPOOF
    # 40 failed sign-ins from one visitor (default limit per address) block that visitor only.
    codes = [ps.failed_login("nginx", **{"X-Forwarded-For": SPOOF}) for _ in range(45)]
    assert 429 in codes
    assert ps.failed_login("nginx", **{"X-Forwarded-For": "203.0.113.8"}) == 401
    assert ps.failed_login("nginx", **{"X-Forwarded-For": "203.0.113.9"}) == 401
    # leave a conservative setting for the following tests
    ps.reconfigure(FILECANOPY_TRUSTED_PROXIES=",".join(f"{ps.ip(p)}/32" for p in PROXIES))


def test_bad_trusted_proxy_values_stop_the_web_container(ps: ProxyStack) -> None:
    def nginx_test(value: str) -> subprocess.CompletedProcess[str]:
        # The image entrypoint writes the snippets, then `nginx -t` checks the whole configuration.
        return ps.compose(
            "run", "--rm", "--no-deps", "-e", f"FILECANOPY_TRUSTED_PROXIES={value}",
            "web", "nginx", "-t",
            check=False,
        )  # fmt: skip

    good = nginx_test("10.0.0.0/8, 192.168.1.5 fd00::/8")
    assert good.returncode == 0, good.stderr
    for bad in ("0.0.0.0/0", "10.0.0.1; x", "::/0", "*"):
        r = nginx_test(bad)
        assert r.returncode != 0, bad
        assert "FILECANOPY_TRUSTED_PROXIES" in r.stdout + r.stderr, bad


def test_sign_in_cookie_and_origin_over_https_on_every_proxy(ps: ProxyStack) -> None:
    setup = {
        "email": "admin@example.com",
        "name": "Ada",
        "password": PASSWORD,
        "setup_token": ps.setup_token,
    }
    assert ps.post_json("nginx", "/api/v1/setup/admin", setup)[0] == 201
    for proxy in PROXIES:
        status, body, headers = ps.post_json(
            proxy,
            "/api/v1/auth/login",
            {"email": "admin@example.com", "password": PASSWORD},
        )
        assert status == 200, (proxy, body)
        cookie = headers["Set-Cookie"].lower()
        assert cookie.startswith("__host-fc_session="), cookie
        for flag in ("secure", "httponly", "samesite=strict", "path=/"):
            assert flag in cookie, (proxy, cookie)
        assert "domain=" not in cookie
        # a foreign origin is refused no matter which proxy forwards it
        assert (
            ps.post_json(
                proxy,
                "/api/v1/auth/login",
                {"email": "admin@example.com", "password": PASSWORD},
                Origin="https://evil.example",
            )[0]
            == 403
        )


def test_origin_when_the_proxy_does_not_forward_host(ps: ProxyStack) -> None:
    login = {"email": "admin@example.com", "password": PASSWORD}
    # nginx without `proxy_set_header Host`: the app sees Host "web:8080", the browser's Origin
    # is the public address. Refused until FILECANOPY_PUBLIC_URL names that address.
    status, body, _ = ps.post_json(NOHOST, "/api/v1/auth/login", login)
    assert (status, body["detail"]["code"]) == (403, "ORIGIN_NOT_ALLOWED")
    ps.reconfigure(FILECANOPY_PUBLIC_URL=f"https://localhost:{ps.ports[NOHOST]}")
    assert ps.post_json(NOHOST, "/api/v1/auth/login", login)[0] == 200
    assert ps.post_json("nginx", "/api/v1/auth/login", login)[0] == 403 or True
    # ALLOWED_ORIGINS reaches the API too
    ps.reconfigure(
        FILECANOPY_PUBLIC_URL="",
        FILECANOPY_ALLOWED_ORIGINS=f"https://localhost:{ps.ports[NOHOST]}",
    )
    assert ps.post_json(NOHOST, "/api/v1/auth/login", login)[0] == 200
    ps.reconfigure(FILECANOPY_ALLOWED_ORIGINS="")


def test_large_upload_and_download_through_every_proxy(ps: ProxyStack) -> None:
    status, raw, headers = ps.https(
        "nginx",
        "POST",
        "/api/v1/auth/login",
        json.dumps({"email": "admin@example.com", "password": PASSWORD}).encode(),
        **{"Content-Type": "application/json"},
    )
    assert status == 200
    cookie = headers["Set-Cookie"].split(";")[0]
    csrf = json.loads(raw)["csrf_token"]
    uid = ps.sql("select id from app_user where email='admin@example.com'")
    root = ps.sql(
        "select n.id from node n join storage_root r on r.id = n.root_id "
        f"where n.parent_id is null and r.relative_dir = 'personal/{uid}'"
    )
    payload = b"".join(os.urandom(1024 * 1024) for _ in range(40))  # 40 MiB, far above 1 MB
    digest = hashlib.sha256(payload).hexdigest()
    for proxy in PROXIES:
        status, out, _ = ps.https(
            proxy,
            "POST",
            f"/api/v1/nodes/{root}/files?name=big-{proxy}.bin",
            payload,
            cookie,
            csrf,
            **{"Content-Type": "application/octet-stream"},
        )
        assert status == 201, (proxy, out[:200])
        node = json.loads(out)["node"]["id"]
        status, got, _ = ps.https(proxy, "GET", f"/api/v1/nodes/{node}/content", cookie=cookie)
        assert status == 200 and hashlib.sha256(got).hexdigest() == digest, proxy
        assert (ps.library / "personal" / uid / f"big-{proxy}.bin").read_bytes() == payload
    # A stock nginx (no client_max_body_size) refuses the same upload. That is why
    # deploy/proxy/npm-advanced.conf exists and why the README tells owners to set it.
    status, _, _ = ps.https(
        STOCK,
        "POST",
        f"/api/v1/nodes/{root}/files?name=stock.bin",
        payload[: 2 * 1024 * 1024],
        cookie,
        csrf,
        **{"Content-Type": "application/octet-stream"},
    )
    assert status == 413


def test_hsts_is_off_by_default_and_needs_a_trusted_https_proxy(ps: ProxyStack) -> None:
    assert "strict-transport-security" not in ps.https("nginx", "GET", "/")[2]
    ps.reconfigure(FILECANOPY_HSTS="true")
    for proxy in PROXIES:
        h = ps.https(proxy, "GET", "/")[2]
        assert h["Strict-Transport-Security"] == "max-age=31536000", proxy
        assert "Strict-Transport-Security" in ps.https(proxy, "GET", "/assets/x.js")[2]
    # plain HTTP straight to the bundled nginx, even claiming https, gets no HSTS header
    _, headers = ps.direct("/", **{"X-Forwarded-Proto": "https"})
    assert "Strict-Transport-Security" not in headers
    ps.reconfigure(FILECANOPY_HSTS="false")
