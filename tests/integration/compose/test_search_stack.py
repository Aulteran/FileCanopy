"""M11 against the real stack: migration 0013 (generated tsvector column and GIN index on
PostgreSQL), the background indexer, and a full-text query with `websearch_to_tsquery`.

Run after the auth and storage suites (they perform the first-run setup this one reuses). Random
credentials and generated bytes only."""

import time
import uuid
from urllib.parse import quote

import pytest
from test_files_stack import js
from test_stack import Stack
from test_trash_stack import Member

pytestmark = pytest.mark.compose


@pytest.fixture
def stack(app_stack: Stack) -> Stack:
    return app_stack


def test_the_search_schema_and_a_full_text_query_on_postgresql(stack: Stack) -> None:
    assert stack.sql(
        "select count(*) from information_schema.columns "
        "where table_name = 'search_doc' and column_name = 'tsv'"
    ) == ("1")
    assert stack.sql("select count(*) from pg_indexes where indexname = 'ix_search_doc_tsv'") == (
        "1"
    )
    alice = Member(stack, "alice")
    bob = Member(stack, "bob")
    word = "zyx" + uuid.uuid4().hex[:8]
    alice.upload(alice.root, "plan.txt", f"The quarterly {word} budget and other words".encode())
    path = f"/api/v1/search?q={quote(word)}"
    deadline = time.monotonic() + 90
    hits: list[dict[str, str]] = []
    while time.monotonic() < deadline:  # the indexer scans every few seconds
        status, out = js(alice.client, "GET", path)
        assert status == 200, out
        hits = out["hits"]
        if hits:
            break
        time.sleep(2)
    assert [h["name"] for h in hits] == ["plan.txt"] and hits[0]["match"] == "content"
    assert word in (hits[0]["snippet"] or "")
    # another member's search never sees it, and websearch syntax cannot break the query
    status, out = js(bob.client, "GET", path)
    assert status == 200 and out["hits"] == []
    for odd in ('"unclosed quote', "a & | ! b", "-", "'; drop table node; --"):
        status, out = js(alice.client, "GET", f"/api/v1/search?q={quote(odd)}")
        assert status == 200, (odd, out)
    status, out = js(alice.client, "GET", f"/api/v1/search?q={quote('plan')}")
    assert status == 200 and [h["name"] for h in out["hits"]] == ["plan.txt"]
