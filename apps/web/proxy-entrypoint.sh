#!/bin/sh
# Runs at container start (nginx image /docker-entrypoint.d). Turns two settings into nginx
# snippets under /tmp (a tmpfs; the container filesystem is read-only):
#   FILECANOPY_TRUSTED_PROXIES  comma- or space-separated IPs/CIDRs of reverse proxies in front of
#                               this container. Default empty: trust nobody.
#   FILECANOPY_HSTS             "true" adds Strict-Transport-Security, only on requests a trusted
#                               proxy says arrived over https. Default off.
# Values are validated strictly; a bad value stops the container (fail closed) instead of
# producing a config that trusts too much.
set -eu
set -f  # no glob expansion of the values below

http=/tmp/fc-http.conf
server=/tmp/fc-realip.conf
trusted=$(printf '%s' "${FILECANOPY_TRUSTED_PROXIES:-}" | tr ',' ' ')

geo=""
real=""
for entry in $trusted; do
    # A very short prefix trusts a huge part of the internet (1.2.3.4/0 is everything), so refuse
    # IPv4 prefixes shorter than /8 and IPv6 prefixes shorter than /16.
    case "$entry" in
        */*)
            prefix=${entry#*/}
            case "$prefix" in
                *[!0-9]* | "") prefix=999 ;;
            esac
            case "$entry" in
                *:*) min=16 ;;
                *) min=8 ;;
            esac
            if [ "$prefix" -lt "$min" ]; then
                echo "FILECANOPY_TRUSTED_PROXIES: refusing '$entry' (too wide: trusting a large range defeats the check; list your proxy's own address)" >&2
                exit 1
            fi ;;
    esac
    if ! printf '%s' "$entry" | grep -Eq '^[0-9A-Fa-f:.]+(/[0-9]{1,3})?$' ||
       ! printf '%s' "$entry" | grep -Eq '[.:]'; then
        echo "FILECANOPY_TRUSTED_PROXIES: '$entry' is not an IP address or CIDR range" >&2
        exit 1
    fi
    geo="${geo}    ${entry} 1;
"
    real="${real}set_real_ip_from ${entry};
"
done

case "$(printf '%s' "${FILECANOPY_HSTS:-false}" | tr 'A-Z' 'a-z')" in
    true | 1 | yes | on) hsts="max-age=31536000" ;;
    false | 0 | no | off | "") hsts="" ;;
    *) echo "FILECANOPY_HSTS must be true or false" >&2; exit 1 ;;
esac

{
    echo "# generated by proxy-entrypoint.sh"
    # $realip_remote_addr is the direct peer even after the realip module rewrote $remote_addr.
    echo 'geo $realip_remote_addr $fc_trusted_peer {'
    echo '    default 0;'
    printf '%s' "$geo"
    echo '}'
    # The scheme is believed only from a trusted peer; otherwise it is what nginx itself saw.
    echo 'map "$fc_trusted_peer:$http_x_forwarded_proto" $fc_proto {'
    echo '    default $scheme;'
    echo '    "1:https" https;'
    echo '    "1:http" http;'
    echo '}'
    echo 'map $fc_proto $fc_hsts {'
    echo '    default "";'
    if [ -n "$hsts" ]; then echo "    https \"$hsts\";"; fi
    echo '}'
} > "$http"

{
    echo "# generated by proxy-entrypoint.sh"
    if [ -n "$real" ]; then
        printf '%s' "$real"
        echo 'real_ip_header X-Forwarded-For;'
        echo 'real_ip_recursive on;'
    fi
} > "$server"
